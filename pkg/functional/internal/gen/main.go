// Command gen generates the fixed-arity members of package functional:
// Tuple2..Tuple9 and the ZipOption/ZipResult/ZipValidation helpers that
// build them.
//
// Go has no variadic generics. A tuple over N type parameters — and a Zip that
// takes N Options and yields one Option of an N-tuple — cannot be written once
// and reused across arities: each arity is a separate declaration differing
// from its neighbours only mechanically. That is what generation is for. Eight
// hand-written near-copies invite exactly the transcription slip (a Third that
// returns t.Second) that a template cannot make.
//
// Run it with `go generate ./pkg/functional/...`.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// minArity is 2 because a one-element tuple is just the value. maxArity is 9
// to match the ceiling the wider Go ecosystem settled on; past that, a named
// struct communicates far more than a positional Ninth ever will.
const (
	minArity = 2
	maxArity = 9
)

var (
	typeParamNames = []string{"A", "B", "C", "D", "E", "F", "G", "H", "I"}
	fieldNames     = []string{
		"First", "Second", "Third", "Fourth", "Fifth", "Sixth", "Seventh", "Eighth", "Ninth",
	}
	valueNames = []string{
		"first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth",
	}
	numberWords = []string{"two", "three", "four", "five", "six", "seven", "eight", "nine"}
)

// arity carries every fragment the templates need for one N, precomputed here
// so the templates stay free of loops and index arithmetic.
type arity struct {
	N                int
	Word             string
	TypeParams       string // "A, B"
	TypeArgs         string // "A, B"
	FieldDecls       string // "First A\nSecond B"
	CtorParams       string // "first A, second B"
	CtorInits        string // "First: first, Second: second"
	UnpackValues     string // "t.First, t.Second"
	OptionParams     string // "a Option[A], b Option[B]"
	ResultParams     string // "a Result[A], b Result[B]"
	ValidationParams string // "a Validation[A], b Validation[B]"
	ErrArgs          string // "a.err, b.err"
	ErrsArgs         string // "a.errs, b.errs"
	NotPresentCond   string // "!a.IsPresent() || !b.IsPresent()"
	ValueArgs        string // "a.v, b.v"
}

func newArity(n int) arity {
	types := typeParamNames[:n]
	fields := fieldNames[:n]
	values := valueNames[:n]

	var (
		fieldDecls       []string
		ctorParams       []string
		ctorInits        []string
		unpackValues     []string
		optionParams     []string
		resultParams     []string
		validationParams []string
		errArgs          []string
		errsArgs         []string
		notPresentCond   []string
		valueArgs        []string
	)
	for i, typ := range types {
		short := strings.ToLower(typ)
		fieldDecls = append(fieldDecls, fmt.Sprintf("%s %s", fields[i], typ))
		ctorParams = append(ctorParams, fmt.Sprintf("%s %s", values[i], typ))
		ctorInits = append(ctorInits, fmt.Sprintf("%s: %s", fields[i], values[i]))
		unpackValues = append(unpackValues, "t."+fields[i])
		optionParams = append(optionParams, fmt.Sprintf("%s Option[%s]", short, typ))
		resultParams = append(resultParams, fmt.Sprintf("%s Result[%s]", short, typ))
		validationParams = append(validationParams, fmt.Sprintf("%s Validation[%s]", short, typ))
		errArgs = append(errArgs, short+".err")
		errsArgs = append(errsArgs, short+".errs")
		notPresentCond = append(notPresentCond, "!"+short+".IsPresent()")
		valueArgs = append(valueArgs, short+".v")
	}

	joined := strings.Join(types, ", ")
	return arity{
		N:                n,
		Word:             numberWords[n-minArity],
		TypeParams:       joined,
		TypeArgs:         joined,
		FieldDecls:       strings.Join(fieldDecls, "\n"),
		CtorParams:       strings.Join(ctorParams, ", "),
		CtorInits:        strings.Join(ctorInits, ", "),
		UnpackValues:     strings.Join(unpackValues, ", "),
		OptionParams:     strings.Join(optionParams, ", "),
		ResultParams:     strings.Join(resultParams, ", "),
		ValidationParams: strings.Join(validationParams, ", "),
		ErrArgs:          strings.Join(errArgs, ", "),
		ErrsArgs:         strings.Join(errsArgs, ", "),
		NotPresentCond:   strings.Join(notPresentCond, " || "),
		ValueArgs:        strings.Join(valueArgs, ", "),
	}
}

const tupleTemplate = `// Code generated by internal/gen. DO NOT EDIT.

package functional
{{range .}}
// Tuple{{.N}} groups {{.Word}} values of possibly different types. It carries no
// absence or failure state of its own — it exists so one step in a chain can
// hand more than one value to the next without an ad hoc struct.
type Tuple{{.N}}[{{.TypeParams}} any] struct {
{{.FieldDecls}}
}

// NewTuple{{.N}} builds a Tuple{{.N}} from its {{.Word}} values.
func NewTuple{{.N}}[{{.TypeParams}} any]({{.CtorParams}}) Tuple{{.N}}[{{.TypeArgs}}] {
	return Tuple{{.N}}[{{.TypeArgs}}]{ {{.CtorInits}} }
}

// Unpack returns the values as separate results, so a caller can bind them all
// in one statement instead of reading fields one at a time.
func (t Tuple{{.N}}[{{.TypeArgs}}]) Unpack() ({{.TypeArgs}}) {
	return {{.UnpackValues}}
}
{{end}}`

const zipTemplate = `// Code generated by internal/gen. DO NOT EDIT.

package functional
{{range .}}
// ZipOption{{.N}} combines {{.Word}} independent Options into one Option carrying
// a Tuple{{.N}} of their values. Use it when the lookups do not depend on each
// other; when a later lookup is keyed by an earlier one's value, chain with
// FlatMap instead.
//
// The result is present only when every input is present. A failure outranks
// absence — the leftmost error is propagated — so a caller checking Err first
// never mistakes a real failure for a missing value.
func ZipOption{{.N}}[{{.TypeParams}} any]({{.OptionParams}}) Option[Tuple{{.N}}[{{.TypeArgs}}]] {
	if err := firstErr({{.ErrArgs}}); err != nil {
		return Failed[Tuple{{.N}}[{{.TypeArgs}}]](err)
	}
	if {{.NotPresentCond}} {
		return None[Tuple{{.N}}[{{.TypeArgs}}]]()
	}
	return Some(NewTuple{{.N}}({{.ValueArgs}}))
}

// ZipResult{{.N}} combines {{.Word}} independent Results into one Result carrying
// a Tuple{{.N}} of their values. It succeeds only when every input succeeded;
// otherwise the leftmost error is propagated.
func ZipResult{{.N}}[{{.TypeParams}} any]({{.ResultParams}}) Result[Tuple{{.N}}[{{.TypeArgs}}]] {
	if err := firstErr({{.ErrArgs}}); err != nil {
		return Failure[Tuple{{.N}}[{{.TypeArgs}}]](err)
	}
	return Ok(NewTuple{{.N}}({{.ValueArgs}}))
}
{{end}}`

const validationTemplate = `// Code generated by internal/gen. DO NOT EDIT.

package functional
{{range .}}
// ZipValidation{{.N}} combines {{.Word}} independent Validations into one
// Validation carrying a Tuple{{.N}} of their values. This is where Validation
// parts ways with Result: ZipResult{{.N}} propagates only the leftmost error,
// while ZipValidation{{.N}} collects the errors from every invalid input,
// concatenated left to right in argument order — so a caller can render
// field errors in the order the fields appear on the form.
//
// The result is valid only when every input is valid.
func ZipValidation{{.N}}[{{.TypeParams}} any]({{.ValidationParams}}) Validation[Tuple{{.N}}[{{.TypeArgs}}]] {
	if errs := collectErrs({{.ErrsArgs}}); len(errs) > 0 {
		return Validation[Tuple{{.N}}[{{.TypeArgs}}]]{errs: errs}
	}
	return Valid(NewTuple{{.N}}({{.ValueArgs}}))
}
{{end}}`

func main() {
	arities := make([]arity, 0, maxArity-minArity+1)
	for n := minArity; n <= maxArity; n++ {
		arities = append(arities, newArity(n))
	}

	files := []struct {
		name string
		tmpl string
	}{
		{name: "tuple_gen.go", tmpl: tupleTemplate},
		{name: "zip_gen.go", tmpl: zipTemplate},
		{name: "validation_gen.go", tmpl: validationTemplate},
	}

	// go:generate runs with the working directory of the file carrying the
	// directive, which is the package root — the destination for both files.
	for _, f := range files {
		if err := render(f.name, f.tmpl, arities); err != nil {
			fmt.Fprintf(os.Stderr, "gen: %s: %v\n", f.name, err)
			os.Exit(1)
		}
	}
}

func render(name, tmpl string, arities []arity) error {
	t, err := template.New(name).Parse(tmpl)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if execErr := t.Execute(&buf, arities); execErr != nil {
		return fmt.Errorf("execute template: %w", execErr)
	}

	// Format rather than trusting the template's whitespace: the field
	// alignment inside each struct is gofmt's job, not the template's.
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}

	if writeErr := os.WriteFile(filepath.Clean(name), formatted, 0o644); writeErr != nil {
		return fmt.Errorf("write file: %w", writeErr)
	}
	return nil
}
