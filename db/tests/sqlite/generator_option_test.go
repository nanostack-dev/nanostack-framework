package sqlite

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/nanostack-dev/nanostack-framework/db/generator/sqlite"
	"github.com/nanostack-dev/nanostack-framework/db/generator/template"
	sqlite2 "github.com/nanostack-dev/nanostack-framework/db/sqlite"
	"github.com/nanostack-dev/nanostack-framework/db/tests/dbconfig"
	"github.com/nanostack-dev/nanostack-framework/db/tests/internal/testenv"
)

func TestGeneratorOption(t *testing.T) {
	lib := t.TempDir()
	require.NoError(
		t,
		sqlite.GenerateDSN(
			dbconfig.TestSampleDBPath,
			lib,
			template.DefaultWith(sqlite2.Dialect, template.NullableOption),
		),
	)

	got, err := os.ReadFile(filepath.Join(lib, "model", "all_types.go"))
	require.NoError(t, err)
	require.Equal(t, sqliteOptionAllTypes, string(got))
	require.FileExists(t, filepath.Join(lib, "table", "all_types.go"), "DefaultWith keeps the SQL builder")

	// The CLI with -nullable=option -skip-sql-builder writes what the harness template writes.
	want := t.TempDir()
	require.NoError(t, sqlite.GenerateDSN(dbconfig.TestSampleDBPath, want, testenv.OptionTemplate(sqlite2.Dialect)))
	cli := t.TempDir()
	testenv.RunJet(
		t,
		"-source=sqlite",
		"-dsn=file:"+dbconfig.TestSampleDBPath,
		"-nullable=option",
		"-skip-sql-builder",
		"-path="+cli,
	)
	testenv.RequireSameTree(t, want, cli)

	testenv.RequireJetRejectsNullable(t, "-source=sqlite", "-dsn=file:"+dbconfig.TestSampleDBPath, "-path="+t.TempDir())
}

