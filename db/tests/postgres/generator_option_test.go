func TestGeneratorOption(t *testing.T) {
	lib := t.TempDir()
	require.NoError(t, postgres.GenerateDSN(getConnectionString(), "test_sample", lib,
		template.DefaultWith(postgres2.Dialect, template.NullableOption)))

	got, err := os.ReadFile(filepath.Join(lib, "jetdb", "test_sample", "model", "all_types.go"))
	require.NoError(t, err)
	require.FileExists(
		t,
		filepath.Join(lib, "jetdb", "test_sample", "table", "all_types.go"),
		"DefaultWith keeps the SQL builder",
	)
	if sourceIsCockroachDB() {
		// CockroachDB's types differ (wider integers); compare with this run's harness output.
		want, readErr := os.ReadFile(
			filepath.Join(
				testRoot,
				testenv.GenTestDataDir,
				testenv.OptionDir,
				"jetdb",
				"test_sample",
				"model",
				"all_types.go",
			),
		)
		require.NoError(t, readErr)
		require.Equal(t, string(want), string(got))
	} else {
		require.Equal(t, postgresOptionAllTypes, string(got))
	}

	// The CLI with -nullable=option -skip-sql-builder writes what the harness template writes.
	want := t.TempDir()
	require.NoError(
		t,
		postgres.GenerateDSN(getConnectionString(), "test_sample", want, testenv.OptionTemplate(postgres2.Dialect)),
	)
	cli := t.TempDir()
	testenv.RunJet(t, "-source=postgres", "-dsn="+getConnectionString(), "-schema=test_sample",
		"-nullable=option", "-skip-sql-builder", "-path="+cli)
	testenv.RequireSameTree(t, want, cli)

	testenv.RequireJetRejectsNullable(
		t,
		"-source=postgres",
		"-dsn="+getConnectionString(),
		"-schema=test_sample",
		"-path="+t.TempDir(),
	)
}

