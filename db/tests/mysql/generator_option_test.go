func TestGeneratorOption(t *testing.T) {
	dsn := dbconfig.MySQLConnectionString(sourceIsMariaDB(), "test_sample")

	lib := t.TempDir()
	require.NoError(t, mysql.GenerateDSN(dsn, lib, template.DefaultWith(mysql2.Dialect, template.NullableOption)))

	got, err := os.ReadFile(filepath.Join(lib, "test_sample", "model", "all_types.go"))
	require.NoError(t, err)
	require.FileExists(
		t,
		filepath.Join(lib, "test_sample", "table", "all_types.go"),
		"DefaultWith keeps the SQL builder",
	)
	if sourceIsMariaDB() {
		// MariaDB's types differ; compare with this run's harness output.
		want, readErr := os.ReadFile(
			filepath.Join(
				testRoot,
				testenv.GenTestDataDir,
				testenv.OptionDir,
				"mysql",
				"test_sample",
				"model",
				"all_types.go",
			),
		)
		require.NoError(t, readErr)
		require.Equal(t, string(want), string(got))
	} else {
		require.Equal(t, mysqlOptionAllTypes, string(got))
	}

	// The CLI with -nullable=option -skip-sql-builder writes what the harness template writes.
	want := t.TempDir()
	require.NoError(t, mysql.GenerateDSN(dsn, want, testenv.OptionTemplate(mysql2.Dialect)))
	cli := t.TempDir()
	testenv.RunJet(t, "-source=mysql", "-dsn="+dsn, "-nullable=option", "-skip-sql-builder", "-path="+cli)
	testenv.RequireSameTree(t, want, cli)

	testenv.RequireJetRejectsNullable(t, "-source=mysql", "-dsn="+dsn, "-path="+t.TempDir())
}

