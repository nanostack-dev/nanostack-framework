package template

import (
	"fmt"
	"go/format"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/nanostack-dev/nanostack-framework/db/generator/metadata"
	"github.com/nanostack-dev/nanostack-framework/db/internal/utils/filesys"
)

// File is one generated Go file, not yet written.
type File struct {
	// Path is relative to the directory that ProcessSchema would write the
	// schema directory into, slash-separated, such as
	// "public/table/users.go".
	Path string
	// Data is the gofmt-formatted source.
	Data []byte
}

// Render generates the files of one schema in memory, as ProcessSchema
// would write them, and prints nothing. It never touches the disk, so
// deleting the files a schema no longer produces is the caller's job. A file
// that does not format is an error.
func Render(schemaMetaData metadata.Schema, generatorTemplate Template) ([]File, error) {
	if schemaMetaData.IsEmpty() {
		return nil, nil
	}
	schemaTemplate := generatorTemplate.Schema(schemaMetaData)
	out := &memorySink{}
	// The sink sees paths under the schema directory; File.Path keeps the
	// schema directory itself, as ProcessSchema's destination does.
	err := processSchema(out, schemaTemplate.Path, schemaMetaData, generatorTemplate, schemaTemplate)
	if err != nil {
		return nil, err
	}
	return out.files, nil
}

// UseHeader returns a template whose files start with header instead of
// go-jet's "Code generated by go-jet DO NOT EDIT." comment. The header
// should be Go comment lines, such as "// Code generated by nano gen db. DO
// NOT EDIT.\n\n".
func (t Template) UseHeader(header string) Template {
	t.Header = header
	return t
}

func (t Template) header() string {
	if t.Header != "" {
		return t.Header
	}
	return autoGenWarningTemplate
}

// UseUniqueKeys returns a TableSQLBuilder that adds, or not, a UniqueKeys
// method to the table type (unique_keys.go).
func (tb TableSQLBuilder) UseUniqueKeys(uniqueKeys bool) TableSQLBuilder {
	tb.UniqueKeys = uniqueKeys
	return tb
}

// sink receives the generated files of processSchema.
type sink interface {
	ensureDir(dir string) error
	save(dir, fileName string, text []byte) error
	logf(format string, args ...any)
}

// diskSink writes the files and prints progress on stdout, as go-jet does.
type diskSink struct{}

func (diskSink) ensureDir(dir string) error { return filesys.EnsureDirPathExist(dir) }

func (diskSink) save(dir, fileName string, text []byte) error {
	return filesys.FormatAndSaveGoFile(dir, fileName, text)
}

func (diskSink) logf(format string, args ...any) { _, _ = fmt.Fprintf(os.Stdout, format, args...) }

// memorySink keeps the formatted files and prints nothing.
type memorySink struct{ files []File }

func (*memorySink) ensureDir(string) error { return nil }

func (m *memorySink) save(dir, fileName string, text []byte) error {
	if !strings.HasSuffix(fileName, ".go") {
		fileName += ".go"
	}
	name := path.Clean(filepath.ToSlash(filepath.Join(dir, fileName)))
	src, err := format.Source(text)
	if err != nil {
		return fmt.Errorf("failed to format '%s': %w", name, err)
	}
	m.files = append(m.files, File{Path: name, Data: src})
	return nil
}

func (*memorySink) logf(string, ...any) {}
