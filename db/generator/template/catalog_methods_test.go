func textColumn(name, catalogType string) metadata.Column {
	return metadata.Column{
		Name:        name,
		DataType:    metadata.DataType{Name: "text", Kind: metadata.BaseType},
		CatalogType: catalogType,
	}
}

// catalogSchema has a composite foreign key whose referencing columns are in
// another order than the referenced key, a key to another schema, and a
// view, which has no foreign key.
var catalogSchema = metadata.Schema{ //nolint:gochecknoglobals // read-only fixture
	Name: "public",
	TablesMetaData: []metadata.Table{{
		Name: "webhook_requests",
		Columns: []metadata.Column{
			textColumn("id", "text"),
			textColumn("tenant_id", "uuid"),
			textColumn("webhook_id", "text"),
			textColumn("ip_address", "inet"),
			textColumn("headers", "jsonb"),
			textColumn("tags", "_text"),
			{Name: "received_at", DataType: metadata.DataType{Name: "timestamptz", Kind: metadata.BaseType},
				CatalogType: "timestamptz"},
		},
		ForeignKeys: []metadata.ForeignKey{
			{
				Name: "webhook_requests_owner_fkey", Columns: []string{"user_id", "tenant_id"},
				ReferencedSchema: "auth", ReferencedTable: "users", ReferencedColumns: []string{"id", "tenant_id"},
			},
			{
				Name: "webhook_requests_webhook_fkey", Columns: []string{"webhook_id", "tenant_id"},
				ReferencedSchema: "public", ReferencedTable: "webhooks",
				ReferencedColumns: []string{"id", "tenant_id"},
			},
		},
	}},
	ViewsMetaData: []metadata.Table{{
		Name:    "recent_requests",
		Columns: []metadata.Column{textColumn("id", "text")},
	}},
}

func catalogTemplate(dialect jet.Dialect, columnTypes, foreignKeys bool) Template {
	return Default(dialect).UseHeader("// Code generated by nanostack gen db. DO NOT EDIT.\n\n").
		UseSchema(func(s metadata.Schema) Schema {
			return DefaultSchema(s).UseSQLBuilder(DefaultSQLBuilder().UseTable(func(t metadata.Table) TableSQLBuilder {
				return DefaultTableSQLBuilder(t).UseUniqueKeys(true).
					UseColumnTypes(columnTypes).UseForeignKeys(foreignKeys)
			}))
		})
}

// markRead marks every table of schema as read by the ReadSchema function of
// a dialect, which the two methods require.
func markRead(schema metadata.Schema) metadata.Schema {
	schema.TablesMetaData = slices.Clone(schema.TablesMetaData)
	for i := range schema.TablesMetaData {
		schema.TablesMetaData[i].CatalogTypesRead = true
		schema.TablesMetaData[i].ForeignKeysRead = true
	}
	return schema
}

func renderSchema(t *testing.T, schema metadata.Schema, tmpl Template) map[string]string {
	t.Helper()
	files, err := Render(markRead(schema), tmpl)
	require.NoError(t, err)
	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = string(f.Data)
	}
	return out
}

// ColumnTypes lists every column of the table type in column order, by SQL
// name, with the catalogue's type name. It comes after UniqueKeys.
func TestColumnTypesMethod(t *testing.T) {
	t.Parallel()
	table := renderSchema(t, catalogSchema, catalogTemplate(postgres.Dialect, true, false))["public/table/webhook_requests.go"]
	require.Contains(t, table, `
// ColumnTypes lists the catalogue type of each column of webhook_requests, by
// column name: pg_type.typname (the base type at the end of a chain of domains,
// the array type of an array, such as "_text", and "schema.name" for a type of
// another schema than pg_catalog and the schema of the table, or for a type
// that has the name of a pg_catalog type). Generated by nanostack gen db from
// the catalogue. nanostack gen repo reads it to pick keys, literals and the
// operators a column accepts.
func (WebhookRequestsTable) ColumnTypes() map[string]string {
	return map[string]string{
		"id":          "text",
		"tenant_id":   "uuid",
		"webhook_id":  "text",
		"ip_address":  "inet",
		"headers":     "jsonb",
		"tags":        "_text",
		"received_at": "timestamptz",
	}
}
`)
	uniqueKeys, columnTypes := strings.Index(table, ") UniqueKeys()"), strings.Index(table, ") ColumnTypes()")
	require.Positive(t, uniqueKeys)
	require.Less(t, uniqueKeys, columnTypes)
	require.NotContains(t, table, "ForeignKeys")
}

// ForeignKeys lists the keys in the catalogue's order, with the columns of
// each key in key order. ReferencedSchema is set only for a key to another
// schema. The type comes from the dialect package the table file imports.
func TestForeignKeysMethod(t *testing.T) {
	t.Parallel()
	table := renderSchema(t, catalogSchema, catalogTemplate(postgres.Dialect, false, true))["public/table/webhook_requests.go"]
	require.Contains(t, table, `
// ForeignKeys lists the foreign keys of webhook_requests, in constraint name
// order, with the referencing and the referenced columns in key order.
// ReferencedSchema is set only when the referenced table is in another schema.
// Generated by nanostack gen db from the catalogue. nanostack gen repo reads it
// to find the joins that a key declares.
func (WebhookRequestsTable) ForeignKeys() []postgres.ForeignKey {
	return []postgres.ForeignKey{
		{
			Name:              "webhook_requests_owner_fkey",
			Columns:           []string{"user_id", "tenant_id"},
			References:        "users",
			ReferencedColumns: []string{"id", "tenant_id"},
			ReferencedSchema:  "auth",
		},
		{
			Name:              "webhook_requests_webhook_fkey",
			Columns:           []string{"webhook_id", "tenant_id"},
			References:        "webhooks",
			ReferencedColumns: []string{"id", "tenant_id"},
		},
	}
}
`)
	require.NotContains(t, table, "ColumnTypes")
}

// A table with no foreign key gets an empty slice literal; views get neither
// method; with both options off the table file has neither.
func TestCatalogMethodsScope(t *testing.T) {
	t.Parallel()
	schema := metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{
		{Name: "events", Columns: []metadata.Column{textColumn("at", "timestamptz")}},
	}}
	table := renderSchema(t, schema, catalogTemplate(postgres.Dialect, true, true))["public/table/events.go"]
	require.Contains(t, table,
		"func (EventsTable) ForeignKeys() []postgres.ForeignKey {\n\treturn []postgres.ForeignKey{}\n}\n")

	// The view builder turns both options on: views still get neither method.
	tmpl := Default(postgres.Dialect).UseSchema(func(s metadata.Schema) Schema {
		return DefaultSchema(s).UseSQLBuilder(DefaultSQLBuilder().UseView(func(v metadata.Table) ViewSQLBuilder {
			return DefaultViewSQLBuilder(v).UseColumnTypes(true).UseForeignKeys(true)
		}))
	})
	files := renderSchema(t, catalogSchema, tmpl)
	require.NotEmpty(t, files["public/view/recent_requests.go"])
	require.NotContains(t, files["public/view/recent_requests.go"], "ColumnTypes")
	require.NotContains(t, files["public/view/recent_requests.go"], "ForeignKeys")

	off := renderSchema(t, catalogSchema, catalogTemplate(postgres.Dialect, false, false))
	require.NotContains(t, off["public/table/webhook_requests.go"], "ColumnTypes")
	require.NotContains(t, off["public/table/webhook_requests.go"], "ForeignKeys")
}

// On MySQL the type is mysql.ForeignKey, and the value of ColumnTypes keeps
// COLUMN_TYPE as the catalogue gives it.
func TestCatalogMethodsMySQL(t *testing.T) {
	t.Parallel()
	schema := metadata.Schema{Name: "shop", TablesMetaData: []metadata.Table{{
		Name: "orders",
		Columns: []metadata.Column{
			textColumn("status", "enum('NEW','PAID')"),
			textColumn("paid", "tinyint(1)"),
		},
		ForeignKeys: []metadata.ForeignKey{{
			Name: "orders_customer_fk", Columns: []string{"customer_id"},
			ReferencedSchema: "shop", ReferencedTable: "customers", ReferencedColumns: []string{"id"},
		}},
	}}}
	table := renderSchema(t, schema, catalogTemplate(mysql.Dialect, true, true))["shop/table/orders.go"]
	require.Contains(t, table, "// name: information_schema.columns.COLUMN_TYPE (such as \"varchar(255)\",\n")
	require.Contains(t, table, "\t\t\"status\": \"enum('NEW','PAID')\",\n\t\t\"paid\":   \"tinyint(1)\",\n")
	require.Contains(t, table, "func (OrdersTable) ForeignKeys() []mysql.ForeignKey {")
	require.NotContains(t, table, "ReferencedSchema:")
}

// A column whose Go name is the name of a method would be hidden by it: an
// error that names the column, not a silent rename.
func TestCatalogMethodsColumnClash(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ column, goName string }{
		{"column_types", "ColumnTypes"},
		{"foreign_keys", "ForeignKeys"},
	} {
		schema := markRead(metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{
			{Name: "settings", Columns: []metadata.Column{textColumn(tc.column, "text")}},
		}})
		_, err := Render(schema, catalogTemplate(postgres.Dialect, true, true))
		require.ErrorContains(t, err,
			`column "`+tc.column+`" of table "settings" has the Go name `+tc.goName, tc.column)
	}
}

// On SQLite the type is sqlite.ForeignKey, and a key has no name, so Name is
// left out.
func TestForeignKeysSQLite(t *testing.T) {
	t.Parallel()
	schema := metadata.Schema{TablesMetaData: []metadata.Table{{
		Name:    "track",
		Columns: []metadata.Column{textColumn("album_id", "INTEGER")},
		ForeignKeys: []metadata.ForeignKey{{
			Columns: []string{"album_id"}, ReferencedTable: "album", ReferencedColumns: []string{"id"},
		}},
	}}}
	files := renderSchema(t, schema, catalogTemplate(sqlite.Dialect, true, true))
	table := files["/table/track.go"] // SQLite has no schema directory
	require.NotEmpty(t, table, "the files are %v", slices.Collect(maps.Keys(files)))
	require.Contains(t, table, `
func (TrackTable) ForeignKeys() []sqlite.ForeignKey {
	return []sqlite.ForeignKey{
		{
			Columns:           []string{"album_id"},
			References:        "album",
			ReferencedColumns: []string{"id"},
		},
	}
}
`)
	require.Contains(t, table, "// the declared type, as pragma_table_xinfo gives it")
	require.Contains(
		t,
		table,
		"// ForeignKeys lists the foreign keys of track, in the order of\n// pragma_foreign_key_list, without a name (SQLite keeps none), with the\n",
	)
}

// A schema that the ReadSchema function of the dialect did not read (from
// GetSchema, for example) has no catalogue facts: an error, not "" for every
// type and no key for every table. On PostgreSQL and MySQL an empty type is
// an error too; on SQLite it is the type of a column declared without one.
func TestCatalogMethodsNeedReadSchema(t *testing.T) {
	t.Parallel()
	unread := metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{
		{Name: "events", Columns: []metadata.Column{textColumn("at", "timestamptz")}},
	}}
	_, err := Render(unread, catalogTemplate(postgres.Dialect, true, false))
	require.ErrorContains(t, err, `table "events" has no catalogue types: read the schema with the ReadSchema`)
	_, err = Render(unread, catalogTemplate(postgres.Dialect, false, true))
	require.ErrorContains(t, err, `table "events" has no foreign keys from the catalogue: read the schema`)

	empty := markRead(metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{
		{Name: "events", Columns: []metadata.Column{textColumn("at", "")}},
	}})
	for _, dialect := range []jet.Dialect{postgres.Dialect, mysql.Dialect} {
		_, err = Render(empty, catalogTemplate(dialect, true, true))
		require.ErrorContains(t, err, `column "at" of table "events" has no catalogue type`, dialect.Name())
	}
	files := renderSchema(
		t,
		metadata.Schema{TablesMetaData: empty.TablesMetaData},
		catalogTemplate(sqlite.Dialect, true, true),
	)
	require.Contains(t, files["/table/events.go"], "\t\t\"at\": \"\",\n")
}

// A key needs at least one column, and one referenced column per column.
func TestForeignKeysMethodColumnCount(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		columns, referenced []string
		want                string
	}{
		{[]string{"a", "b"}, []string{"id"}, "has 2 columns and 1 referenced columns"},
		{nil, nil, "has 0 columns and 0 referenced columns"},
	} {
		schema := markRead(metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{{
			Name:    "events",
			Columns: []metadata.Column{textColumn("a", "text")},
			ForeignKeys: []metadata.ForeignKey{{
				Name: "events_fkey", Columns: tc.columns, ReferencedTable: "t", ReferencedColumns: tc.referenced,
			}},
		}}})
		_, err := Render(schema, catalogTemplate(postgres.Dialect, false, true))
		require.ErrorContains(t, err, `foreign key "events_fkey" of table "events" `+tc.want)
	}
}

// A column that the table type skips is not in ColumnTypes either.
func TestColumnTypesSkipsColumns(t *testing.T) {
	t.Parallel()
	schema := metadata.Schema{Name: "public", TablesMetaData: []metadata.Table{{
		Name:    "events",
		Columns: []metadata.Column{textColumn("at", "timestamptz"), textColumn("secret", "bytea")},
	}}}
	tmpl := Default(postgres.Dialect).UseSchema(func(s metadata.Schema) Schema {
		return DefaultSchema(s).UseSQLBuilder(DefaultSQLBuilder().UseTable(func(t metadata.Table) TableSQLBuilder {
			b := DefaultTableSQLBuilder(t).UseColumnTypes(true)
			return b.UseColumn(func(c metadata.Column) TableSQLBuilderColumn {
				col := DefaultTableSQLBuilderColumn(c)
				col.Skip = c.Name == "secret"
				return col
			})
		}))
	})
	table := renderSchema(t, schema, tmpl)["public/table/events.go"]
	require.Contains(t, table, "\t\t\"at\": \"timestamptz\",\n")
	require.NotContains(t, table, `"secret"`)
}
