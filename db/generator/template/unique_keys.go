package template

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/nanostack-dev/nanostack-framework/db/generator/metadata"
)

// uniqueKeysMethod returns the UniqueKeys method of a table type: the keys
// of table.UniqueIndexes that prove a match of at most one row, by index
// name, with their key columns in index order. Each other unique index is a
// "Not a key" line of the doc comment, with its reason. nano gen repo reads
// the method with go/parser to prove that a derived method returns at most
// one row, so it needs no database.
func uniqueKeysMethod(table metadata.Table, builder TableSQLBuilder) (string, error) {
	for _, c := range table.Columns {
		if col := builder.Column(c); !col.Skip && col.Name == "UniqueKeys" {
			return "", fmt.Errorf("column %q of table %q has the Go name UniqueKeys, "+
				"which the generated UniqueKeys method would hide: rename the column", c.Name, table.Name)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "\n// UniqueKeys lists the keys of %s that match at most one row, by constraint\n", table.Name)
	b.WriteString("// or index name, with the key columns in index order: the primary key and every\n" +
		"// valid, immediate unique index without an expression key whose predicate, if\n" +
		"// any, is \"<key column> IS NOT NULL\". Generated by nano gen db from the\n" +
		"// catalogue. nano gen repo reads it to prove a derived single-row method.\n")
	for _, ix := range table.UniqueIndexes {
		if ix.NotKey != "" {
			fmt.Fprintf(&b, "// Not a key: %s: %s.\n", ix.Name, oneLine(ix.NotKey))
		}
	}
	fmt.Fprintf(&b, "func (%s) UniqueKeys() map[string][]string {\n\treturn map[string][]string{\n", builder.TypeName)
	for _, ix := range table.UniqueIndexes {
		if ix.NotKey != "" {
			continue
		}
		cols := make([]string, len(ix.Columns))
		for i, c := range ix.Columns {
			cols[i] = strconv.Quote(c)
		}
		fmt.Fprintf(&b, "\t\t%s: {%s},", strconv.Quote(ix.Name), strings.Join(cols, ", "))
		if ix.Predicate != "" {
			b.WriteString(" // WHERE " + oneLine(ix.Predicate))
		}
		b.WriteString("\n")
	}
	b.WriteString("\t}\n}\n")
	return b.String(), nil
}

// oneLine keeps a catalogue text on one comment line.
func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
