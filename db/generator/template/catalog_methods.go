// columnTypesMethod returns the ColumnTypes method of a table type: the
// catalogue type of each column the table type has, by SQL column name, in
// column order (metadata.Column.CatalogType). nanostack gen repo reads the method
// with go/parser to pick keys, literals and the operators a column accepts,
// so it needs no database.
func columnTypesMethod(table metadata.Table, builder TableSQLBuilder, dialect jet.Dialect) (string, error) {
	if err := checkMethodName(table, builder, "ColumnTypes"); err != nil {
		return "", err
	}
	if !table.CatalogTypesRead {
		return "", fmt.Errorf("table %q has no catalogue types: %s", table.Name, readSchemaHint)
	}
	var b strings.Builder
	b.WriteString("\n")
	b.WriteString(docComment("ColumnTypes lists the catalogue type of each column of " + table.Name +
		", by column name: " + columnTypesSource[dialect.PackageName()] + ". Generated by nanostack gen db " +
		"from the catalogue. nanostack gen repo reads it to pick keys, literals and the operators a column accepts."))
	fmt.Fprintf(&b, "func (%s) ColumnTypes() map[string]string {\n\treturn map[string]string{\n", builder.TypeName)
	for _, c := range table.Columns {
		if builder.Column(c).Skip {
			continue
		}
		if c.CatalogType == "" && dialect.PackageName() != "sqlite" { // "" is a declared type only on SQLite
			return "", fmt.Errorf("column %q of table %q has no catalogue type: %s", c.Name, table.Name,
				readSchemaHint)
		}
		fmt.Fprintf(&b, "\t\t%s: %s,\n", strconv.Quote(c.Name), strconv.Quote(c.CatalogType))
	}
	b.WriteString("\t}\n}\n")
	return b.String(), nil
}

// readSchemaHint says how to get a schema that has the catalogue facts.
const readSchemaHint = "read the schema with the ReadSchema function of the dialect " +
	"(GetSchema does not read the catalogue types and the foreign keys)"

// columnTypesSource says where the types of ColumnTypes come from, by
// dialect package.
var columnTypesSource = map[string]string{ //nolint:gochecknoglobals // read-only table
	"postgres": `pg_type.typname (the base type at the end of a chain of domains, the array type ` +
		`of an array, such as "_text", and "schema.name" for a type of another schema than ` +
		`pg_catalog and the schema of the table, or for a type that has the name of a pg_catalog type)`,
	"mysql":  `information_schema.columns.COLUMN_TYPE (such as "varchar(255)", "tinyint(1)" or "enum('a','b')")`,
	"sqlite": `the declared type, as pragma_table_xinfo gives it ("" for a column declared without a type)`,
}

// foreignKeyOrder says in which order ForeignKeys lists the keys, by dialect
// package.
var foreignKeyOrder = map[string]string{ //nolint:gochecknoglobals // read-only table
	"postgres": "in constraint name order",
	"mysql":    "in constraint name order",
	"sqlite":   "in the order of pragma_foreign_key_list, without a name (SQLite keeps none)",
}

// foreignKeysMethod returns the ForeignKeys method of a table type: the
// foreign keys of table.ForeignKeys, in the order the reader gives them,
// with the referencing and the referenced columns in key order. Name is left
// out when the catalogue has none (SQLite), and ReferencedSchema unless the
// key is to a table of another schema. The element type is the ForeignKey
// alias of the dialect package that the table file already imports. nanostack gen
// repo reads the method with go/parser to find the joins that a key declares.
func foreignKeysMethod(
	table metadata.Table,
	builder TableSQLBuilder,
	dialect jet.Dialect,
	schema string,
) (string, error) {
	if err := checkMethodName(table, builder, "ForeignKeys"); err != nil {
		return "", err
	}
	if !table.ForeignKeysRead {
		return "", fmt.Errorf("table %q has no foreign keys from the catalogue: %s", table.Name, readSchemaHint)
	}
	typ := "[]" + dialect.PackageName() + ".ForeignKey"
	var b strings.Builder
	b.WriteString("\n")
	b.WriteString(docComment("ForeignKeys lists the foreign keys of " + table.Name + ", " +
		foreignKeyOrder[dialect.PackageName()] + ", with the referencing and the referenced columns in key " +
		"order. ReferencedSchema is set only when the referenced table is in another schema. Generated by " +
		"nanostack gen db from the catalogue. nanostack gen repo reads it to find the joins that a key declares."))
	fmt.Fprintf(&b, "func (%s) ForeignKeys() %s {\n\treturn %s{", builder.TypeName, typ, typ)
	for _, fk := range table.ForeignKeys {
		if len(fk.Columns) == 0 || len(fk.Columns) != len(fk.ReferencedColumns) {
			return "", fmt.Errorf("foreign key %q of table %q has %d columns and %d referenced columns",
				fk.Name, table.Name, len(fk.Columns), len(fk.ReferencedColumns))
		}
		b.WriteString("\n\t\t{\n")
		if fk.Name != "" { // SQLite keeps no name
			fmt.Fprintf(&b, "\t\t\tName: %s,\n", strconv.Quote(fk.Name))
		}
		fmt.Fprintf(&b, "\t\t\tColumns: %s,\n", stringSlice(fk.Columns))
		fmt.Fprintf(&b, "\t\t\tReferences: %s,\n", strconv.Quote(fk.ReferencedTable))
		fmt.Fprintf(&b, "\t\t\tReferencedColumns: %s,\n", stringSlice(fk.ReferencedColumns))
		if fk.ReferencedSchema != "" && fk.ReferencedSchema != schema {
			fmt.Fprintf(&b, "\t\t\tReferencedSchema: %s,\n", strconv.Quote(fk.ReferencedSchema))
		}
		b.WriteString("\t\t},")
	}
	if len(table.ForeignKeys) > 0 {
		b.WriteString("\n\t")
	}
	b.WriteString("}\n}\n")
	return b.String(), nil
}

// checkMethodName refuses a column whose Go name is the name of a generated
// method: the field would hide the method, or the method the field.
func checkMethodName(table metadata.Table, builder TableSQLBuilder, method string) error {
	for _, c := range table.Columns {
		if col := builder.Column(c); !col.Skip && col.Name == method {
			return fmt.Errorf("column %q of table %q has the Go name %s, "+
				"which the generated %s method would hide: rename the column", c.Name, table.Name, method, method)
		}
	}
	return nil
}

// stringSlice returns the Go literal of a []string.
func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// docComment returns text as // comment lines of at most 80 columns.
func docComment(text string) string {
	const width = 80
	var b strings.Builder
	line := "//"
	for word := range strings.FieldsSeq(text) {
		if len(line)+1+len(word) > width && line != "//" {
			b.WriteString(line + "\n")
			line = "//"
		}
		line += " " + word
	}
	b.WriteString(line + "\n")
	return b.String()
}
