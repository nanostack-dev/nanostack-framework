package nano_test

import (
	"context"

	"github.com/nanostack-dev/nanostack-framework/core/config"
	"github.com/nanostack-dev/nanostack-framework/core/nano"
)

// serviceConfig and bind stand in for the service's Config and the Bind
// that nano gen config writes in its package.
type serviceConfig struct{}

func bind(context.Context, *config.Sources) (serviceConfig, error) { return serviceConfig{}, nil }

// buildApp stands in for the Build that nano gen wire writes in the
// service's wire package: wire.Build(ctx, cfg, wire.Overrides{}).
func buildApp(context.Context, serviceConfig) (*nano.App, error) {
	return nano.NewApp("example", nano.AppConfig{}), nil
}

// A service's main binds its configuration from the profile file and the
// environment, then calls the generated Build.
func ExampleMain() {
	nano.Main(func(ctx context.Context) (*nano.App, error) {
		src, err := config.NewSources(config.ProfileFromEnv("config"), config.Env())
		if err != nil {
			return nil, err
		}
		cfg, err := bind(ctx, src) // app.Bind, generated by nano gen config
		if err != nil {
			return nil, err
		}
		return buildApp(ctx, cfg) // wire.Build(ctx, cfg, wire.Overrides{})
	})
}
