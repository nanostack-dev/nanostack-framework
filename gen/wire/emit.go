package wire

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/nanostack-dev/nanostack-framework/gen/internal/importset"
)

// emitter writes wire.gen.go. It renders twice: the first pass records the
// packages the code uses, then imports and local names are assigned so they
// never collide, and the second pass writes the final source.
type emitter struct {
	g        *graph
	m        *manifest
	collect  bool
	used     map[string]*types.Package // path -> package, collected in pass one
	std      map[string]string         // path -> name for packages without a *types.Package
	imports  *importset.Set            // local names, assigned after pass one
	buf      bytes.Buffer
	reserved map[string]bool
}

func emit(g *graph) ([]byte, error) {
	e := &emitter{
		g:    g,
		m:    g.m,
		used: map[string]*types.Package{},
		std:  map[string]string{},
	}
	e.collect = true
	e.render()
	e.assignNames()
	e.collect = false
	e.buf.Reset()
	e.render()
	src, err := format.Source(e.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf(
			"generated code does not parse (a generator bug): %w\n%s",
			err,
			e.buf.Bytes(),
		)
	}
	return src, nil
}

func (e *emitter) p(format string, args ...any) { fmt.Fprintf(&e.buf, format, args...) }

// pkg returns the local name for an import path, recording it in pass one.
func (e *emitter) pkg(p *types.Package) string {
	if p.Path() == e.m.outPath {
		return ""
	}
	if e.collect {
		e.used[p.Path()] = p
		return p.Name()
	}
	return e.imports.Name(p.Path())
}

func (e *emitter) stdPkg(importPath, name string) string {
	if e.collect {
		e.std[importPath] = name
		return name
	}
	return e.imports.Name(importPath)
}

func (e *emitter) qualifier(p *types.Package) string { return e.pkg(p) }

func (e *emitter) typ(t types.Type) string { return types.TypeString(t, e.qualifier) }

func (e *emitter) nano() string {
	if e.m.outPath == NanoPath {
		return ""
	}
	return e.stdPkg(NanoPath, "nano") + "."
}

func (e *emitter) render() {
	m := e.m
	e.p("// Code generated by nano gen wire from %s. DO NOT EDIT.\n\n", e.sourcePath())
	e.p("//go:build !%s\n\n", buildTag)
	e.p("package %s\n\n", m.outName)

	// The import block is written last, once pass one knows every package.
	head := e.buf.Len()
	body := e.renderBody()
	e.buf.Truncate(head)
	e.renderImports()
	e.buf.Write(body)
}

func (e *emitter) sourcePath() string {
	rel, err := filepath.Rel(e.m.modDir, e.m.file)
	if err != nil {
		return filepath.Base(e.m.file)
	}
	return filepath.ToSlash(rel)
}

func (e *emitter) renderImports() {
	if e.collect {
		return
	}
	var b strings.Builder
	e.imports.Write(&b)
	e.buf.WriteString(b.String())
}

func (e *emitter) renderBody() []byte {
	start := e.buf.Len()
	m, g := e.m, e.g
	nano := e.nano()
	ctxPkg := e.stdPkg("context", "context")
	errorsPkg := e.stdPkg("errors", "errors")

	switch {
	case m.config != nil && !m.samePkg:
		e.p("// Config is the configuration Build reads, declared next to the manifest.\n")
		e.p("type Config = %s\n\n", e.typ(m.config))
	case m.config == nil:
		e.p("// Config is empty: the manifest package declares no Config type.\n")
		e.p("type Config struct{}\n\n")
	}
	e.renderStructs()

	e.p("// Build constructs the %s app. It calls each needed provider once, in\n", m.appName)
	e.p("// dependency order, and registers every component's lifecycle with the App.\n")
	e.p("// If a provider fails, Build stops what it already constructed.\n")
	e.p("func Build(ctx %s.Context, cfg Config, ov Overrides) (*%sApp, error) {\n", ctxPkg, nano)
	e.p("\tapp, _, err := BuildComponents(ctx, cfg, ov)\n\treturn app, err\n}\n\n")

	e.p("// BuildComponents is Build that also returns the values it constructed.\n")
	e.p("func BuildComponents(ctx %s.Context, cfg Config, ov Overrides) (_ *%sApp, _ *Components, err error) {\n",
		ctxPkg, nano)
	e.p("\tapp := %sNewApp(%q, %s)\n", nano, m.appName, strings.Replace(g.appCfg, "nano.", nano, 1))
	e.p("\tdefer func() {\n\t\tif err != nil {\n\t\t\terr = %s.Join(err, app.Stop(ctx))\n\t\t}\n\t}()\n", errorsPkg)

	if len(g.order) > 0 {
		e.p("\n\t// A value is built only when something that runs needs it and no\n")
		e.p("\t// override replaces the value that needs it.\n")
		for _, n := range slices.Backward(g.order) {
			e.p("\t%s := %s\n", n.needName, e.demand(n))
		}
	}
	for _, n := range g.order {
		e.p("\n")
		e.renderNode(n)
	}
	if len(g.invokes) > 0 {
		e.p("\n")
	}
	for _, inv := range g.invokes {
		call := fmt.Sprintf("%s(%s)", e.funcRef(inv.p), e.args(inv.deps))
		if !inv.p.errRet {
			e.p("\t%s\n", call)
			continue
		}
		e.p("\tif err = %s; err != nil {\n", call)
		e.p("\t\treturn nil, nil, %s\n\t}\n", e.wrap("invoke "+funcName(inv.p.fn)))
	}
	e.p("\treturn app, &Components{")
	for i, n := range g.order {
		if i > 0 {
			e.p(", ")
		}
		e.p("%s: %s", n.field, n.varName)
	}
	e.p("}, nil\n}\n")

	out := slices.Clone(e.buf.Bytes()[start:])
	return out
}

func (e *emitter) renderStructs() {
	g := e.g
	e.p("// Overrides replaces provided values, mostly in tests. A nil field keeps the\n")
	e.p("// production provider. A set field skips that provider, and every provider\n")
	e.p("// only it needed, Starters and Runners included; the App manages the\n")
	e.p("// override's lifecycle instead. A Starter or Runner that nothing takes is\n")
	e.p("// always built.\n")
	e.p("type Overrides struct {\n")
	for _, n := range g.order {
		e.p("\t%s %s\n", n.field, e.overrideType(n.typ))
	}
	e.p("}\n\n")

	e.p("// Components holds the values BuildComponents constructed, for tests that\n")
	e.p("// need to reach them. A field holds the override when one was set, and the\n")
	e.p("// zero value when no built value needed it.\n")
	e.p("type Components struct {\n")
	for _, n := range g.order {
		e.p("\t%s %s\n", n.field, e.typ(n.typ))
	}
	e.p("}\n\n")
}

// demand returns the expression that decides whether Build constructs n.
// An invoked value, and a Starter or Runner that nothing takes, is always
// built. Any other value is built when a consumer that is built needs it and
// is not overridden; without overrides that is every value in the graph.
func (e *emitter) demand(n *node) string {
	if n.invoked || n.root && len(n.consumers) == 0 {
		return "true"
	}
	terms := make([]string, 0, len(n.consumers))
	for _, c := range n.consumers {
		terms = append(terms, fmt.Sprintf("%s && ov.%s == nil", c.needName, c.field))
	}
	if len(terms) == 1 {
		return terms[0]
	}
	for i, t := range terms {
		terms[i] = "(" + t + ")"
	}
	return strings.Join(terms, " || ")
}

func (e *emitter) renderNode(n *node) {
	name := strconv.Quote(e.m.typeString(n.typ))
	e.p("\tvar %s %s\n", n.varName, e.typ(n.typ))
	e.p("\tif %s {\n", n.needName)
	e.p("\t\tif ov.%s != nil {\n", n.field)
	if nilable(n.typ) {
		e.p("\t\t\t%s = ov.%s\n", n.varName, n.field)
	} else {
		e.p("\t\t\t%s = *ov.%s\n", n.varName, n.field)
	}
	switch n.kind {
	case nodeBind:
		// A binding's implementation registered its own lifecycle; only an
		// override is a new value.
		e.p("\t\t\tapp.Manage(%s, %s)\n", name, n.varName)
		e.p("\t\t} else {\n")
		e.p("\t\t\t%s = %s\n", n.varName, n.deps[0].ref())
		e.p("\t\t}\n\t}\n")
	case nodeCollect:
		// Members registered their own lifecycle; an override's elements are
		// new values.
		if n.life.describe() != "" {
			elem := strconv.Quote(e.m.typeString(n.p.elem))
			e.p("\t\t\tfor _, elem := range %s {\n\t\t\t\tapp.Manage(%s, elem)\n\t\t\t}\n", n.varName, elem)
		}
		e.p("\t\t} else {\n")
		e.p("\t\t\t%s = %s{%s}\n", n.varName, e.typ(n.typ), e.args(n.deps))
		e.p("\t\t}\n\t}\n")
	case nodeFunc:
		e.renderCall(n, name)
	case nodeBuiltin, nodeAmbiguous: // never in the order
	}
}

func (e *emitter) renderCall(n *node, name string) {
	m := e.m
	e.p("\t\t} else {\n")
	call := fmt.Sprintf("%s(%s)", e.funcRef(n.p), e.args(n.deps))
	fail := func() string {
		return "return nil, nil, " + e.wrap("provide "+m.typeString(n.typ)+": "+m.providerLabel(n.p))
	}
	switch {
	case n.p.clean:
		e.p("\t\t\tvar cleanup func()\n")
		e.p("\t\t\t%s, cleanup, err = %s\n", n.varName, call)
		e.p("\t\t\tif err != nil {\n\t\t\t\t%s\n\t\t\t}\n", fail())
		e.p("\t\t\tapp.OnCleanup(%s, cleanup)\n", name)
	case n.p.errRet:
		e.p("\t\t\t%s, err = %s\n", n.varName, call)
		e.p("\t\t\tif err != nil {\n\t\t\t\t%s\n\t\t\t}\n", fail())
	default:
		e.p("\t\t\t%s = %s\n", n.varName, call)
	}
	e.p("\t\t}\n")
	// Manage registers a value once, so a provider that returns one of its
	// dependencies as an interface does not register that component twice.
	if what := n.life.describe(); what != "" {
		e.p("\t\tapp.Manage(%s, %s) // %s\n", name, n.varName, what)
	}
	if n.life.logger {
		e.p("\t\tapp.SetLogger(%s)\n", n.varName)
	}
	e.p("\t}\n")
}

// describe names what Manage registers, for the generated comment, or ""
// when there is nothing to register.
func (l lifecycle) describe() string {
	if l.dynamic {
		return "interface: lifecycle by dynamic type"
	}
	var parts []string
	for _, c := range []struct {
		has  bool
		name string
	}{{l.start, "Starter"}, {l.stop, "Stopper"}, {l.run, "Runner"}, {l.check, "HealthChecker"}} {
		if c.has {
			parts = append(parts, c.name)
		}
	}
	return strings.Join(parts, ", ")
}

func (n *node) ref() string {
	if n.kind == nodeBuiltin {
		return n.expr
	}
	return n.varName
}

func (e *emitter) args(deps []*node) string {
	parts := make([]string, len(deps))
	for i, d := range deps {
		parts[i] = d.ref()
	}
	return strings.Join(parts, ", ")
}

func (e *emitter) wrap(what string) string {
	format := "nano: " + strings.ReplaceAll(what, "%", "%%") + ": %w"
	return fmt.Sprintf("%s.Errorf(%s, err)", e.stdPkg("fmt", "fmt"), strconv.Quote(format))
}

func (e *emitter) funcRef(p *provider) string {
	ref := p.fn.Name()
	if q := e.pkg(p.fn.Pkg()); q != "" {
		ref = q + "." + ref
	}
	if len(p.targs) > 0 {
		args := make([]string, len(p.targs))
		for i, t := range p.targs {
			args[i] = e.typ(t)
		}
		ref += "[" + strings.Join(args, ", ") + "]"
	}
	return ref
}

func (e *emitter) overrideType(t types.Type) string {
	if nilable(t) {
		return e.typ(t)
	}
	return "*" + e.typ(t)
}
