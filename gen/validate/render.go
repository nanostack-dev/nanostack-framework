// fixedImports are the packages that generated code names directly, as in
// "validate.Path" or "regexp.MustCompile": each must get exactly this name.
var fixedImports = map[string]string{ //nolint:gochecknoglobals // read-only table.
	runtimePath:              "validate",
	"encoding/json/jsontext": "jsontext",
	"maps":                   "maps",
	"regexp":                 "regexp",
	"slices":                 "slices",
	"unicode/utf8":           "utf8",
}

// runtimePath is the import path of the validation runtime.
const runtimePath = "github.com/nanostack-dev/nanostack-framework/core/validate"

// localNames are the identifiers generated methods declare. An import with
// one of these names would be shadowed inside the method.
var localNames = []string{"dec", "errs", "ok", "p", "r", "v", "verrs"} //nolint:gochecknoglobals // read-only table.

// newImports returns the import set of a file in pkg. It blocks the names pkg
// declares and the generated locals, then claims the fixed imports' names, so
// a package of the user's that is also named "validate" gets another name.
func newImports(pkg *types.Package) *importset.Set {
	s := importset.New(pkg.Path())
	s.Block(pkg.Scope().Names()...)
	s.Block(localNames...)
	for _, p := range slices.Sorted(maps.Keys(fixedImports)) {
		s.Reserve(p, fixedImports[p])
	}
	return s
}

// use imports one of the fixedImports. It fails generation when the package
// declares the name that generated code uses for it.
func (g *generator) use(path string) {
	want := fixedImports[path]
	if got := g.imports.Add(path, want); got != want && !g.renamed[path] {
		g.renamed[path] = true
		fix := fmt.Sprintf("rename %s in package %s", want, g.gp.pkg.Path())
		if obj := g.gp.pkg.Scope().Lookup(want); obj != nil {
			g.goErrorf(obj.Pos(), fix, "package %s declares %s, which the generated file needs as the name of %s",
				g.gp.pkg.Path(), want, path)
		} else {
			g.errorf(fix, "package %s declares %s, which the generated file needs as the name of %s",
				g.gp.pkg.Path(), want, path)
		}
	}
}

// qualifier prints types of other packages with their import name.
func (g *generator) qualifier(p *types.Package) string { return g.imports.Qualifier(p) }

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, g.qualifier)
}

func (g *generator) pattern(loc, p string) (string, bool) {
	re, err := translatePattern(p)
	if err != nil {
		g.errorf("rewrite the pattern in the part of ECMA-262 that RE2 supports", "%s: %v", loc, err)
		return "", false
	}
	if name, ok := g.patterns[re]; ok {
		return name, true
	}
	name := "pattern" + strconv.Itoa(len(g.patOrder)+1)
	g.patterns[re] = name
	g.patOrder = append(g.patOrder, re)
	g.use("regexp")
	return name, true
}

func (g *generator) render(specRel string) ([]byte, error) {
	methods := make([]*method, 0, len(g.methods))
	for _, m := range g.methods {
		methods = append(methods, m)
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].named.Obj().Name() < methods[j].named.Obj().Name() })
	sort.Slice(g.params, func(i, j int) bool { return g.params[i].req.Obj().Name() < g.params[j].req.Obj().Name() })
	integers := g.integerTypes()
	if len(methods) > 0 || len(g.params) > 0 || len(integers) > 0 {
		g.use(runtimePath)
	}
	if len(integers) > 0 {
		g.use("encoding/json/jsontext")
	}
	if len(g.errs) > 0 {
		return nil, oas.JoinErrors(g.errs)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by nano gen validate from %s. DO NOT EDIT.\n\n", commentText(specRel))
	fmt.Fprintf(&b, "package %s\n\n", g.gp.pkg.Name())
	g.renderImports(&b)
	g.renderPreamble(&b)
	for _, m := range methods {
		name := m.named.Obj().Name()
		fmt.Fprintf(&b, "// Validate checks r against %s.\n", commentText(m.schema.Loc))
		fmt.Fprintf(&b, "func (r %s) Validate(p validate.Path) validate.Errors {\n", name)
		if m.body == "" {
			b.WriteString("return nil\n}\n\n")
			fmt.Fprintf(&b, "func (%s) validateInto(validate.Path, *validate.Errors) {}\n\n", name)
			continue
		}
		b.WriteString("var errs validate.Errors\nr.validateInto(p, &errs)\nreturn errs\n}\n\n")
		// Nested values write into the caller's accumulator, so its bound
		// holds across the whole document and a loop can stop when it is full.
		fmt.Fprintf(&b, "// validateInto records the violations of r at p in errs.\n")
		fmt.Fprintf(&b, "func (r %s) validateInto(p validate.Path, errs *validate.Errors) {\n%s}\n\n", name, m.body)
	}
	for _, pm := range g.params {
		fmt.Fprintf(&b, "// validateParams checks the parameters of %s %s.\n",
			commentText(pm.op.Method), commentText(pm.op.Path))
		fmt.Fprintf(&b, "func (r %s) validateParams() validate.Errors {\n", pm.req.Obj().Name())
		if pm.body == "" {
			b.WriteString("return nil\n}\n\n")
			continue
		}
		fmt.Fprintf(&b, "errs := new(validate.Errors)\np := validate.Root\n%sreturn *errs\n}\n\n", pm.body)
	}
	for _, tn := range integers {
		fmt.Fprintf(&b, "// UnmarshalJSONFrom decodes a JSON number with an integer value, such as 2 or 2.0.\n")
		fmt.Fprintf(&b, "func (v *%s) UnmarshalJSONFrom(dec *jsontext.Decoder) error {\n", tn.Name())
		b.WriteString("return validate.DecodeInteger(dec, v)\n}\n\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, gen.Errorf("", 0, "report this nano gen validate bug with the spec",
			"format generated code: %v\n%s", err, b.String())
	}
	return src, nil
}

// commentText makes spec text safe inside a // comment or on a terminal: it
// escapes line breaks, every other control character and the Unicode line
// and paragraph separators as strconv.Quote does, without the quotes. A
// string with none of them comes back unchanged.
func commentText(s string) string {
	if !strings.ContainsFunc(s, needsEscape) {
		return s
	}
	var b strings.Builder
	for _, r := range s {
		if needsEscape(r) {
			q := strconv.QuoteRune(r)
			b.WriteString(q[1 : len(q)-1])
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func needsEscape(r rune) bool {
	return unicode.IsControl(r) || r == '\u2028' || r == '\u2029'
}

// renderImports writes the import block: the standard library, a blank
// line, then the others.
func (g *generator) renderImports(b *bytes.Buffer) {
	var sb strings.Builder
	g.imports.Write(&sb)
	b.WriteString(sb.String())
}

// renderPreamble lists what is not enforced and declares the patterns.
func (g *generator) renderPreamble(b *bytes.Buffer) {
	if diags := g.diagnostics(); len(diags) > 0 {
		b.WriteString("// The spec uses these features, which the validators below do not enforce:\n//\n")
		for _, d := range diags {
			fmt.Fprintf(b, "//   - %s\n", d) // Diagnostic.String escapes the spec text
		}
		b.WriteString("\n")
	}
	if len(g.patOrder) > 0 {
		b.WriteString("var (\n")
		for _, re := range g.patOrder {
			fmt.Fprintf(b, "%s = regexp.MustCompile(%s)\n", g.patterns[re], strconv.Quote(re))
		}
		b.WriteString(")\n\n")
	}
}

func (g *generator) paramsBody(pm *paramsMethod) string {
	st, _ := structOf(pm.req)
	var params *types.Struct
	if f, ok := fieldNamed(st, "Params"); ok {
		params, _ = structOf(f.Type())
	}
	var b strings.Builder
	for _, prm := range pm.op.Params {
		if prm.Schema == nil {
			continue
		}
		owner, expr := st, "r"
		if prm.In != "path" {
			if params == nil {
				g.errorf(
					regenerateFix,
					"%s: %s has no Params field for %s parameter %q",
					prm.Loc,
					pm.req.Obj().Name(),
					prm.In,
					prm.Name,
				)
				continue
			}
			owner, expr = params, "r.Params"
		}
		f, ok := fieldByJSON(owner, prm.Name)
		if !ok {
			g.errorf(regenerateFix, "%s: no Go field for %s parameter %q in %s",
				prm.Loc, prm.In, prm.Name, pm.req.Obj().Name())
			continue
		}
		path := fmt.Sprintf("p.Field(%q)", prm.Name)
		b.WriteString(g.value(prm.Schema, expr+"."+f.Name(), f.Type(), path, ctx{}))
	}
	return b.String()
}

func fieldNamed(st *types.Struct, name string) (*types.Var, bool) {
	for f := range st.Fields() {
		if f.Name() == name {
			return f, true
		}
	}
	return nil, false
}

// integerTypes returns the named integer types of the package, such as
// integer enums, that decode with json/v2's default rules. Each gets an
// UnmarshalJSONFrom method so that, like Go's own integer types under
// validate.DecodeOptions, it accepts a JSON number with an integer value
// written with a fraction or exponent (2.0, 2e0), as JSON Schema defines
// integer.
func (g *generator) integerTypes() []*types.TypeName {
	var out []*types.TypeName
	scope := g.gp.pkg.Scope()
	for _, name := range scope.Names() { // sorted
		tn, ok := scope.Lookup(name).(*types.TypeName)
		if !ok || tn.IsAlias() || !tn.Exported() {
			continue
		}
		n, ok := tn.Type().(*types.Named)
		if !ok || n.TypeParams().Len() > 0 {
			continue
		}
		basic, ok := n.Underlying().(*types.Basic)
		if !ok || basic.Info()&types.IsInteger == 0 || basic.Kind() == types.Uintptr {
			continue
		}
		if hasMethod(n, g.gp.pkg, "UnmarshalJSONFrom", "UnmarshalJSON", "UnmarshalText") {
			continue
		}
		out = append(out, tn)
	}
	return out
}

// hasMethod reports whether *n has a method with one of names.
func hasMethod(n *types.Named, pkg *types.Package, names ...string) bool {
	for _, name := range names {
		if obj, _, _ := types.LookupFieldOrMethod(types.NewPointer(n), true, pkg, name); obj != nil {
			if _, isFunc := obj.(*types.Func); isFunc {
				return true
			}
		}
	}
	return false
}
