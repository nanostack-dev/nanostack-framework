// ExemptionsFile is the file, relative to the directory nano gen runs on,
// that lists every tenant exemption of every search of the module (design
// S6.6). nano gen writes it after the repo step, and -check reports it
// stale when a declaration changes an exemption.
const ExemptionsFile = "nanogen/search-exemptions.txt"

// Exemption is one line of the exemption file: an Unscoped column, a
// ScopeOrNull or ScopeNull on a tenant column, a coverage by rule 3, an
// IgnoresFullText or an APIHandWritten.
type Exemption struct {
	Search string
	Text   string
}

func (e Exemption) String() string { return "search " + e.Search + ": " + e.Text }

// ExemptionsData renders the exemption file from its lines, in their order.
func ExemptionsData(lines []string) []byte {
	var b strings.Builder
	b.WriteString("# Code generated by nano gen repo. DO NOT EDIT.\n")
	b.WriteString("# Every tenant exemption of every search of the module (ADR 0027), one per line.\n")
	b.WriteString("# Review each line that a change adds.\n")
	for _, line := range lines {
		b.WriteString(line + "\n")
	}
	return []byte(b.String())
}

// exemptions returns the exemptions of the searches of d, in source order.
func exemptions(d *declarations) []Exemption {
	var out []Exemption
	for _, s := range d.searches {
		for _, text := range s.exemptions {
			out = append(out, Exemption{Search: s.name, Text: text})
		}
		if s.ignoresFullText != "" {
			out = append(out, Exemption{Search: s.name, Text: "IgnoresFullText: " + s.ignoresFullText})
		}
		if len(s.apiHandWritten) > 0 {
			out = append(out, Exemption{Search: s.name, Text: "APIHandWritten " + strings.Join(s.apiHandWritten, ", ")})
		}
	}
	return out
}

// checkUnscoped checks that each Unscoped column leaves another hard tenant
// column of its instance covered (E30): a search is never unscoped as a
// whole, and a context scope can return TRUE.
func (t *tenantCheck) checkUnscoped() {
	for _, u := range t.s.unscoped {
		n := t.outerNode(u.col)
		other := ""
		for _, col := range n.tenant {
			if col == u.col.col.sqlName || t.isContext(col) {
				continue
			}
			if n.how[col] != "" {
				other = col
				break
			}
		}
		if other != "" {
			continue
		}
		fix := "remove Unscoped: a search is never unscoped as a whole"
		for _, col := range n.tenant {
			if col != u.col.col.sqlName && !t.isContext(col) {
				fix = "nanorepo.Scope(" + t.columnText(n, col) + ")"
				break
			}
		}
		t.c.errorf(u.col.expr, fix, "search %s: Unscoped(%s) leaves %s with no other covered hard tenant column",
			t.s.name, u.col, n.inst)
	}
}

// checkCovered reports each instance that no rule covers: a subquery that
// no foreign key correlates (E8), a tenant column (E9), an instance with no
// tenant column (E10).
func (t *tenantCheck) checkCovered() {
	for _, n := range t.nodes {
		switch {
		case n.covered():
		case n.first:
			t.uncorrelated(n)
		case len(n.tenant) > 0:
			t.uncoveredColumns(n)
		default:
			t.unlinked(n)
		}
	}
}

// uncovered returns the tenant columns of n that no rule covers.
func (n *tenantNode) uncovered() []string {
	var out []string
	for _, col := range n.tenant {
		if n.how[col] == "" && n.exempt[col] == "" {
			out = append(out, col)
		}
	}
	return out
}

// uncorrelated reports a subquery instance that its WHERE does not
// correlate on a declared foreign key to a covered instance (E8).
func (t *tenantCheck) uncorrelated(n *tenantNode) {
	what := "it has no WHERE"
	for _, eq := range t.eqs {
		if eq.in == n && eq.a.node != nil && eq.b.node != nil {
			inner, outer := eq.a, eq.b
			if outer.node == n {
				inner, outer = outer, inner
			}
			what = "it equates " + inner.col + " with " + outer.node.inst.name() + "." + outer.col
			break
		}
	}
	if n.cond != nil && what == "it has no WHERE" {
		what = "WHERE " + t.c.source(n.cond)
	}
	t.c.errorf(n.inst.node, t.correlationFix(n), "%s: the subquery on %s is not correlated on a declared foreign "+
		"key to a covered instance of search %s (%s)", n.role, n.inst, t.s.name, what)
}

// correlationFix is the WHERE on a declared foreign key between n and a
// covered instance of the read set.
func (t *tenantCheck) correlationFix(n *tenantNode) string {
	text := n.inst.text
	if n.inst.alias != "" {
		text += `.AS("` + n.inst.alias + `")`
	}
	for _, m := range t.nodes {
		if m.level != 0 || !m.covered() {
			continue
		}
		mText := m.inst.text
		if m.inst.alias != "" {
			mText += `.AS("` + m.inst.alias + `")`
		}
		if on, ok := fkCondition(n.inst.table, text, m.inst.table, mText); ok {
			return "correlate it on its foreign key: WHERE(" + on + ")"
		}
	}
	return "correlate it on a declared foreign key to a covered instance, or write the search by hand"
}

// uncoveredColumns reports the tenant columns of n that no rule covers (E9).
func (t *tenantCheck) uncoveredColumns(n *tenantNode) {
	cols := n.uncovered()
	if len(cols) == 0 { // every column exempted: checkUnscoped reports it
		return
	}
	var fix string
	switch {
	case n.level > 0:
		fix = "equate " + t.columnText(n, cols[0]) + " in the WHERE of the subquery with a covered tenant " +
			"column, or correlate the subquery on a declared foreign key"
	case n.inst.nullable:
		fix = "equate " + t.columnText(n, cols[0]) + " in the ON clause with a covered tenant column, or join " +
			n.inst.String() + " on a declared foreign key from a covered instance"
	case t.isContext(cols[0]):
		fix = "nanorepo.ScopeFunc(" + t.registeredName(cols[0]) + ", " + t.columnText(n, cols[0]) + ")"
	default:
		fix = "nanorepo.Scope(" + t.columnText(n, cols[0]) + "), or nanorepo.Unscoped(" + t.columnText(n, cols[0]) +
			", \"<why>\") when another tenant column of " + n.inst.name() + " is scoped"
	}
	where := "search " + t.s.name
	if n.level > 0 {
		where = n.role + " (search " + t.s.name + ")"
	}
	if len(cols) == 1 {
		t.c.errorf(t.nodeAt(n), fix, "%s: %s.%s is a tenant column and no rule covers it: it would read every "+
			"tenant's rows", where, n.inst.name(), cols[0])
		return
	}
	t.c.errorf(t.nodeAt(n), fix, "%s: %s.%s are tenant columns and no rule covers them: it would read every "+
		"tenant's rows", where, n.inst.name(), strings.Join(cols, ", "))
}

// unlinked reports an instance with no tenant column that no foreign key
// links to a covered instance, and a root that only a LEFT JOIN links
// (E10).
func (t *tenantCheck) unlinked(n *tenantNode) {
	s := t.s
	if n.inst == s.root {
		for _, m := range t.nodes {
			if m.level == 0 && m.inst.join == "LEFT JOIN" && m.covered() {
				if _, ok := t.fkMatch(n, m, m); !ok {
					if _, ok = t.fkMatch(m, n, m); !ok {
						continue
					}
				}
				t.c.errorf(t.nodeAt(n), "join "+m.inst.String()+" with INNER_JOIN, so that its foreign key "+
					"covers "+n.inst.String(), "search %s: %s has no tenant column, and only the LEFT JOIN of %s "+
					"links it to a covered table: its rows exist without that join", s.name, n.inst, m.inst)
				return
			}
		}
	}
	fix := "join " + n.inst.String() + " on a declared foreign key to a covered instance"
	if n.inst == s.root {
		fix = t.rootFix()
	}
	t.c.errorf(t.nodeAt(n), fix, "search %s: %s has no tenant column, and no INNER JOIN on a declared foreign "+
		"key links it to a covered table", s.name, n.inst)
}

// rootFix is the fix of a root with no tenant column: the join on a
// foreign key of the root to a table with a tenant column.
func (t *tenantCheck) rootFix() string {
	root := t.s.root.table
	for _, k := range root.foreignKeys {
		target, ok := t.c.tableBySQLName(k.references)
		if !ok || len(k.columns) != 1 {
			continue
		}
		var tenant []string
		for _, col := range target.columns {
			if slices.Contains(t.c.l.scopes, col.sqlName) {
				tenant = append(tenant, col.sqlName)
			}
		}
		if len(tenant) > 0 {
			return "join " + target.sqlName + " in the From function on " + k.name + ", and scope " +
				target.sqlName + "." + strings.Join(tenant, ", ")
		}
	}
	return "join a table with a tenant column in the From function on a declared foreign key, and scope it"
}

// tableBySQLName returns a table that a search of the package reads.
func (c *collector) tableBySQLName(name string) (*tableBase, bool) {
	for _, t := range c.searchTables {
		if t != nil && t.sqlName == name {
			return t, true
		}
	}
	return nil, false
}

// nodeAt is where a problem of n is reported: its place in the join, or
// the table of the search.
func (t *tenantCheck) nodeAt(n *tenantNode) ast.Node {
	if n.inst.node != nil {
		return n.inst.node
	}
	return t.s.tableNode
}

// columnText renders a column of n as a declaration writes it:
// table.Webhooks.WorkspaceID, or table.Webhooks.AS("w2").WorkspaceID.
func (t *tenantCheck) columnText(n *tenantNode, sqlName string) string {
	text := n.inst.text
	if n.inst.alias != "" {
		text += `.AS("` + n.inst.alias + `")`
	}
	field, _ := fieldOf(n.inst.table, sqlName)
	return text + "." + field
}

// record keeps what the tenant check proved: the exemptions of the search,
// and one -explain line per instance.
func (t *tenantCheck) record() {
	s := t.s
	for _, u := range s.unscoped {
		s.exemptions = append(s.exemptions, "Unscoped "+t.outerNode(u.col).inst.name()+"."+u.col.col.sqlName+
			": "+u.why)
	}
	for _, sc := range s.scopes {
		if sc.kind == "Scope" {
			continue
		}
		for _, col := range sc.cols {
			n := t.outerNode(col)
			if slices.Contains(n.tenant, col.col.sqlName) {
				s.exemptions = append(s.exemptions, sc.kind+" "+n.inst.name()+"."+col.col.sqlName)
			}
		}
	}
	for _, n := range t.nodes {
		if n.rule3 != "" {
			s.exemptions = append(s.exemptions, n.inst.String()+" ("+strings.Join(n.tenant, ", ")+") by rule 3: "+
				n.rule3)
		}
		s.tenantLines = append(s.tenantLines, t.explainNode(n))
	}
}

// explainNode renders how one instance is covered, for -explain.
func (t *tenantCheck) explainNode(n *tenantNode) string {
	text := n.inst.String()
	if n.level > 0 {
		text = n.role + ": " + text
	}
	if len(n.tenant) == 0 {
		if n.inst == t.s.root && n.linked == "" {
			return text + ": no tenant column"
		}
		return text + ": no tenant column; " + n.linked
	}
	parts := make([]string, len(n.tenant))
	for i, col := range n.tenant {
		how := n.how[col]
		if how == "" {
			how = "Unscoped"
		}
		parts[i] = col + " by " + how
	}
	return text + ": " + strings.Join(parts, "; ")
}

// checkUnkeyedScopes refuses an unkeyed literal of a generated scope type
// anywhere in the declaring package (E27): the blank field of the type
// refuses one only in another package, and two values of one type could
// change places.
func (c *collector) checkUnkeyedScopes() {
	scopeTypes := c.scopeStructs()
	if len(scopeTypes) == 0 {
		return
	}
	for _, f := range c.l.pkg.Syntax {
		if own(f) {
			continue
		}
		ast.Inspect(f, func(n ast.Node) bool {
			lit, ok := n.(*ast.CompositeLit)
			if !ok || len(lit.Elts) == 0 {
				return true
			}
			id := identOf(ast.Unparen(lit.Type))
			if id == nil || scopeTypes[id.Name] == nil {
				return true
			}
			if _, keyed := lit.Elts[0].(*ast.KeyValueExpr); keyed {
				return true
			}
			c.errorf(lit, c.keyedFix(scopeTypes[id.Name]), "%s{...} has unkeyed fields: two values of one type "+
				"can change places", id.Name)
			return true
		})
	}
}

// scopeStructs maps the name of each generated scope struct (two fields
// or more) to its search.
func (c *collector) scopeStructs() map[string]*searchDecl {
	out := map[string]*searchDecl{}
	for _, s := range c.d.searches {
		fields := 0
		for _, sc := range s.scopes {
			if sc.kind != "ScopeNull" {
				fields++
			}
		}
		if fields > 1 {
			out[s.name+"Scope"] = s
		}
	}
	return out
}

// keyedFix is the keyed literal of the scope type of s.
func (c *collector) keyedFix(s *searchDecl) string {
	var fields []string
	for _, sc := range s.scopes {
		if sc.kind != "ScopeNull" && len(sc.cols) > 0 {
			fields = append(fields, sc.cols[0].col.field+": ...")
		}
	}
	return s.name + "Scope{" + strings.Join(fields, ", ") + "}"
}
