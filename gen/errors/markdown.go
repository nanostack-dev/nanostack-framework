package generrors

import (
	"fmt"
	"net/http"
	"strings"
)

// renderMarkdown writes the human catalogue of the namespace.
func renderMarkdown(c *catalogue) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("<!-- Code generated by nanostack gen errors from %s. DO NOT EDIT. -->\n\n", c.file)
	w("# %s errors\n\n", c.namespace)
	w("Package `%s` declares these errors in `%s`. Every error renders as an RFC 9457\n", c.pkg, c.file)
	w("`application/problem+json` response whose `type` is `%s/%s/<code>` and whose\n", c.typeBase, c.namespace)
	w("`code` extension member is the stable code below.\n\n")

	w("| Code | Status | Title | Fields |\n|---|---|---|---|\n")
	for _, d := range c.errors {
		w(
			"| [`%s`](#%s) | %d %s | %s | %s |\n",
			c.fullCode(d),
			anchor(c.fullCode(d)),
			d.status,
			http.StatusText(d.status),
			cell(d.title),
			fieldList(d, false),
		)
	}
	for _, d := range c.errors {
		w("\n## %s\n\n", c.fullCode(d))
		if d.doc != "" {
			w("%s\n\n", d.doc)
		}
		w("- Type: `%s`\n", c.typeURI(d))
		w("- Status: %d %s\n", d.status, http.StatusText(d.status))
		w("- Title: %s\n", d.title)
		if d.detail != "" {
			w("- Detail: %s\n", d.detail)
		}
		if len(d.params) > 0 {
			w("- Fields: %s\n", fieldList(d, true))
		}
		params := make([]string, len(d.params))
		for i, p := range d.params {
			params[i] = p.name + " " + p.docTyp
		}
		w("- Go: `%s.%s(%s)` returns `*%s.%sError`; match with `errors.Is(err, %s.Err%s)`\n",
			c.pkg, d.name, strings.Join(params, ", "), c.pkg, d.name, c.pkg, d.name)
	}
	return []byte(b.String())
}

func fieldList(d decl, withTypes bool) string {
	if len(d.params) == 0 {
		return "none"
	}
	parts := make([]string, len(d.params))
	for i, p := range d.params {
		parts[i] = "`" + p.name + "`"
		if withTypes {
			parts[i] += " (`" + p.docTyp + "`)"
		}
	}
	return strings.Join(parts, ", ")
}

// anchor mirrors the heading anchors GitHub generates: lower case, dots
// dropped, spaces to hyphens.
func anchor(s string) string {
	return strings.NewReplacer(".", "", " ", "-").Replace(strings.ToLower(s))
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
