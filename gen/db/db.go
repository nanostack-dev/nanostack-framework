// Package gendb implements nanostack gen db: it applies a module's SQL
// migrations to an empty PostgreSQL database and writes the go-jet code of
// one schema, the models and the table types, with the methods UniqueKeys,
// ColumnTypes and ForeignKeys on each table type.
//
// The database is a container of the declared image, started through
// testcontainers, or a scratch database on the server that
// NANO_GEN_DATABASE_URL names, created for the run and dropped after it.
// The migrations run in-process with pg/nanomigrate. The code is rendered in
// memory by the Nanostack DB generator (db/generator), so a run that fails
// writes nothing.
//
// Layout: <Out>/<Name>/<Schema>/{model,table,view,enum}/*.go and
// <Out>/<Name>/nanogen.sum. Every file starts with "Code generated by nanostack
// gen db. DO NOT EDIT.", so the pipeline finds a file the schema no longer
// produces, such as the file of a dropped table, by its header.
//
// nanogen.sum records each input, the image, the schema, the generator
// version and the sha256 of each migration, and the sha256 of each output.
// While every input matches and every listed output matches its hash, with
// no other nanostack gen db file under <Out>/<Name>, a run reads no database: it
// returns the listed files as they are. -fresh ignores nanogen.sum, as CI
// does, so CI proves that the migrations produce the committed code. A miss
// with no database reachable is an environment error (exit 3).
//
// UniqueKeys lists, by index name, the key columns of the primary key and
// of each unique index that proves "equality on these columns matches at
// most one row": valid, immediate, no expression key, no predicate other
// than "<key column> IS NOT NULL", and no key column under a nondeterministic
// collation that the index does not use. Each other unique index is a "Not
// a key" line of its doc comment.
//
// ColumnTypes lists, by column name, the catalogue type of each column:
// the type name from pg_type (the base type at the end of a chain of domains,
// "_text" for a text array or an array of a text domain, the name of an enum,
// and "schema.name" for a type of another schema or a type that has the name
// of a pg_catalog type). ForeignKeys lists the foreign keys of
// the table in constraint name order, with the referencing and the
// referenced columns in key order, and the schema of the referenced table
// when it is not the generated schema.
//
// nanostack gen repo reads the three methods with go/parser, so the repo step
// needs no database.
//
// The pipeline runs this step first, from the Postgres declaration of
// nanogen/project.go; Main is the single run, with the same fields as flags.
