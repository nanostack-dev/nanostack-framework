// Defaults of the Postgres declaration.
const (
	DefaultMigrations = "migrations"
	DefaultOut        = "internal/db/gen"
	DefaultSchema     = "public"
	DefaultImage      = "postgres:18-alpine"
)

// SumFile is the file under <Out>/<Name> that lets a run skip the database.
const SumFile = "nanogen.sum"

// EnvDatabaseURL names a PostgreSQL server to use instead of a container:
// each run creates a scratch database on it and drops it afterwards.
const EnvDatabaseURL = "NANO_GEN_DATABASE_URL"

// header starts every generated Go file; the pipeline's orphan scan reads
// its first line.
const header = "// Code generated by nanostack gen db. DO NOT EDIT.\n\n"

// Options configures one run.
type Options struct {
	// Dir is the directory the paths of Postgres are relative to, the
	// module root in the pipeline. Default: the working directory.
	Dir string
	// Postgres is the declaration. Zero fields take their defaults.
	Postgres project.Postgres
	// Check writes nothing; Run then fails on a stale, missing or orphaned
	// file.
	Check bool
	// Fresh ignores nanogen.sum and always generates from a database.
	Fresh bool
	// Database opens the empty database of the run. Nil opens one on a
	// Server for DatabaseURL, or for a container of Postgres.Image, and
	// stops it before Generate returns.
	Database Opener
	// DatabaseURL is the value of NANO_GEN_DATABASE_URL, for a nil
	// Database.
	DatabaseURL string
}

// Opener returns an empty database and the function that drops it. An
// error is an *gen.Error that wraps gen.ErrEnvironment, with the fix.
type Opener func(ctx context.Context) (db *sql.DB, drop func(), err error)

// WithDefaults returns p with each empty field set to its default.
func WithDefaults(p project.Postgres) project.Postgres {
	p.Migrations = orDefault(p.Migrations, DefaultMigrations)
	p.Out = orDefault(p.Out, DefaultOut)
	p.Schema = orDefault(p.Schema, DefaultSchema)
	p.Image = orDefault(p.Image, DefaultImage)
	return p
}

// layout holds the absolute paths of one declaration.
type layout struct {
	root, migrations, out string
	p                     project.Postgres
}

func newLayout(dir string, p project.Postgres) (layout, error) {
	root, err := filepath.Abs(orDefault(dir, "."))
	if err != nil {
		return layout{}, gen.EnvErrorf("run from a directory that exists", "resolve %s: %v", dir, err)
	}
	p = WithDefaults(p)
	return layout{
		root:       root,
		migrations: filepath.Join(root, filepath.FromSlash(p.Migrations)),
		out:        filepath.Join(root, filepath.FromSlash(p.Out), p.Name),
		p:          p,
	}, nil
}

// rel returns path relative to the root, slash-separated, for messages.
func (l layout) rel(path string) string {
	if r, err := filepath.Rel(l.root, path); err == nil {
		return filepath.ToSlash(r)
	}
	return filepath.ToSlash(path)
}

// Planned returns the absolute paths of the outputs known before a run:
// nanogen.sum and every file it lists. The pipeline plans them, so its
// orphan scan keeps the committed code on a run that reads no database.
func Planned(dir string, p project.Postgres) []string {
	l, err := newLayout(dir, p)
	if err != nil {
		return nil
	}
	out := []string{filepath.Join(l.out, SumFile)}
	if s, readErr := readSum(l.out); readErr == nil {
		for _, o := range s.outputs {
			out = append(out, filepath.Join(l.out, filepath.FromSlash(o.path)))
		}
	}
	return out
}

// Generate returns the files of the schema, and nanogen.sum. It writes
// nothing. A run whose inputs and outputs match nanogen.sum returns the
// listed files as they are and opens no database.
func Generate(opts Options) ([]gen.File, error) {
	l, err := newLayout(opts.Dir, opts.Postgres)
	if err != nil {
		return nil, err
	}
	if l.p.Name == "" {
		return nil, gen.Errorf("", 0, "set Postgres.Name, the directory under "+l.p.Out+", such as the database name",
			"Postgres.Name is empty")
	}
	migrations, err := readMigrations(l)
	if err != nil {
		return nil, err
	}
	inputs := inputLines(l.p, migrations)
	reason := "-fresh ignores " + SumFile
	if !opts.Fresh {
		files, miss, hitErr := cached(l, inputs)
		if hitErr != nil || miss == "" {
			return files, hitErr
		}
		reason = miss
	}
	return generate(l, opts, inputs, reason)
}

// generate opens a database, migrates it and renders the schema.
func generate(l layout, opts Options, inputs []line, reason string) ([]gen.File, error) {
	ctx := context.Background()
	open := opts.Database
	if open == nil {
		server := NewServer(opts.DatabaseURL, l.p.Image)
		defer server.Close()
		open = server.Open
	}
	db, drop, err := open(ctx)
	if err != nil {
		return nil, unreachable(reason, err)
	}
	defer drop()
	cfg := nanomigrate.DefaultConfig()
	cfg.BasePath = l.migrations
	cfg.Validate = false
	if err = nanomigrate.NewMigrator(cfg, db, slog.New(slog.DiscardHandler)).Migrate(ctx); err != nil {
		return nil, gen.Errorf(l.rel(l.migrations), 0,
			"fix the migration, or set Postgres.Image to an image that has the extensions it needs, "+
				"then run nanostack gen again",
			"the migrations fail on an empty database: %v", err)
	}
	schema, err := jetpostgres.ReadSchema(db, l.p.Schema)
	if err != nil {
		return nil, gen.EnvErrorf("check that the database server is reachable, then run nanostack gen again",
			"read schema %s: %v", l.p.Schema, err)
	}
	if schema.IsEmpty() {
		return nil, gen.Errorf(l.rel(l.migrations), 0,
			"create a table in schema "+l.p.Schema+", or set Postgres.Schema to the schema the migrations fill",
			"the migrations leave schema %s empty", l.p.Schema)
	}
	rendered, err := template.Render(schema, jetTemplate())
	if err != nil {
		return nil, gen.Errorf(l.rel(l.migrations), 0,
			"change the schema as the message says, then run nanostack gen again",
			"render schema %s: %v", l.p.Schema, err)
	}
	files := make([]gen.File, 0, len(rendered)+1)
	outputs := make([]line, 0, len(rendered))
	for _, f := range rendered {
		files = append(files, gen.File{Path: filepath.Join(l.out, filepath.FromSlash(f.Path)), Data: f.Data})
		outputs = append(outputs, line{kind: "output", path: f.Path, hash: digest(f.Data)})
	}
	slices.SortFunc(outputs, func(a, b line) int { return strings.Compare(a.path, b.path) })
	sum := sumFile{inputs: inputs, outputs: outputs}
	return append(files, gen.File{Path: filepath.Join(l.out, SumFile), Data: sum.bytes()}), nil
}

// unreachable reports a cache miss with no database to generate from.
func unreachable(reason string, err error) error {
	e := &gen.Error{Msg: err.Error(), Fix: "start Docker, or set " + EnvDatabaseURL, Err: gen.ErrEnvironment}
	if ge, ok := errors.AsType[*gen.Error](err); ok {
		e = &gen.Error{Msg: ge.Msg, Fix: ge.Fix, Err: gen.ErrEnvironment}
	}
	e.Msg = reason + ", and " + e.Msg
	return e
}

// jetTemplate is the go-jet template of the step: go-jet's defaults
// (pointers for nullable columns, as the services' models have today), the
// nano header, and UniqueKeys, ColumnTypes and ForeignKeys on each table
// type.
func jetTemplate() template.Template {
	return template.Default(postgres.Dialect).
		UseHeader(header).
		UseSchema(func(s metadata.Schema) template.Schema {
			return template.DefaultSchema(s).UseSQLBuilder(
				template.DefaultSQLBuilder().UseTable(func(t metadata.Table) template.TableSQLBuilder {
					return template.DefaultTableSQLBuilder(t).
						UseUniqueKeys(true).UseColumnTypes(true).UseForeignKeys(true)
				}))
		})
}

// migrationName is golang-migrate's file name: <version>_<title>.<up|down>.<ext>.
var migrationName = regexp.MustCompile(`^[0-9]+_.*\.(down|up)\..+$`)

// migration is one migration file, by name.
type migration struct {
	name string
	data []byte
}

// readMigrations reads the migration files that golang-migrate applies.
func readMigrations(l layout) ([]migration, error) {
	entries, err := os.ReadDir(l.migrations)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return nil, gen.Errorf(l.rel(l.migrations), 0,
			"create the directory, or set Postgres.Migrations to the directory of the migrations",
			"the migrations directory does not exist")
	case err != nil:
		return nil, &gen.Error{File: l.rel(l.migrations), Msg: err.Error(),
			Fix: "make the directory readable", Err: gen.ErrEnvironment}
	}
	var out []migration
	for _, e := range entries {
		// golang-migrate applies every entry that is not a directory, a
		// symbolic link included, so each one is an input of nanogen.sum.
		if e.IsDir() || !migrationName.MatchString(e.Name()) {
			continue
		}
		data, readErr := os.ReadFile(filepath.Join(l.migrations, e.Name()))
		if readErr != nil {
			return nil, &gen.Error{File: l.rel(filepath.Join(l.migrations, e.Name())), Msg: readErr.Error(),
				Fix: "make the file readable", Err: gen.ErrEnvironment}
		}
		out = append(out, migration{name: e.Name(), data: data})
	}
	if len(out) == 0 {
		return nil, gen.Errorf(l.rel(l.migrations), 0,
			"add a migration such as 000001_init.up.sql, or set Postgres.Migrations to the directory that holds them",
			"the migrations directory holds no migration file")
	}
	return out, nil
}

// Run generates and writes the files that changed, and deletes each nanostack
// gen db file under <Out>/<Name> that the run did not produce. With Check
// it writes nothing and fails on a stale, missing or orphaned file.
func Run(opts Options) error {
	_, err := run(opts)
	return err
}

// run is Run, and returns the paths it wrote or deleted.
func run(opts Options) ([]string, error) {
	files, err := Generate(opts)
	if err != nil {
		return nil, err
	}
	l, err := newLayout(opts.Dir, opts.Postgres)
	if err != nil {
		return nil, err
	}
	orphans := orphansOf(l, files)
	written, err := gen.Sync("db", files, opts.Check)
	var problems []error
	if err != nil {
		problems = append(problems, err)
	}
	for _, o := range orphans {
		if opts.Check {
			problems = append(problems, gen.Errorf(l.rel(o), 0, "run nanostack gen db without -check, which deletes it",
				"orphan: no table, view or enum of the schema produces it"))
			continue
		}
		if rmErr := os.Remove(o); rmErr != nil {
			problems = append(problems, &gen.Error{File: l.rel(o), Msg: rmErr.Error(),
				Fix: "make the file writable, or delete it by hand", Err: gen.ErrEnvironment})
			continue
		}
		written = append(written, o)
	}
	return written, errors.Join(problems...)
}

// orphansOf returns the nanostack gen db files under <Out>/<Name> that files
// does not hold.
func orphansOf(l layout, files []gen.File) []string {
	produced := map[string]bool{}
	for _, f := range files {
		produced[f.Path] = true
	}
	var out []string
	for _, path := range generatedUnder(l.out) {
		if !produced[path] {
			out = append(out, path)
		}
	}
	return out
}

// generatedUnder returns the files under dir whose first line is the nanostack
// gen db header, sorted.
func generatedUnder(dir string) []string {
	var out []string
	_ = filepath.WalkDir(dir, func(path string, e fs.DirEntry, err error) error {
		if err != nil {
			return nil //nolint:nilerr // a directory that cannot be read holds no output to report
		}
		if e.Type().IsRegular() && isGenerated(path) {
			out = append(out, path)
		}
		return nil
	})
	return out
}

// isGenerated reports whether the first line of the file is the header of
// a nanostack gen db output, in Go or in nanogen.sum.
func isGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	first, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false
	}
	for _, cli := range []string{"nanostack", "nano"} { // nano: written before the CLI was renamed
		if strings.HasPrefix(first, "// Code generated by "+cli+" gen db.") ||
			strings.HasPrefix(first, "# Code generated by "+cli+" gen db.") {
			return true
		}
	}
	return false
}

// Main runs `nanostack gen db -name n [-migrations d] [-out d] [-schema s]
// [-image i] [-dir d] [-fresh] [-check]` and returns the exit code. It
// reads NANO_GEN_DATABASE_URL. It is a gen.Command.
func Main(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("nanostack gen db", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var opts Options
	fs.StringVar(&opts.Dir, "dir", ".", "directory the other paths are relative to")
	fs.StringVar(&opts.Postgres.Name, "name", "", "directory under -out, by convention the database name (required)")
	fs.StringVar(&opts.Postgres.Migrations, "migrations", DefaultMigrations, "directory of the SQL migrations")
	fs.StringVar(&opts.Postgres.Out, "out", DefaultOut, "directory that holds -name")
	fs.StringVar(&opts.Postgres.Schema, "schema", DefaultSchema, "schema to generate")
	fs.StringVar(&opts.Postgres.Image, "image", DefaultImage, "container image, unless "+EnvDatabaseURL+" is set")
	fs.BoolVar(&opts.Fresh, "fresh", false, "ignore "+SumFile+": always generate from a database")
	fs.BoolVar(&opts.Check, "check", false, "write nothing; exit 1 if a generated file is stale, missing or orphaned")
	if exit, ok := gen.ParseFlags(fs, args); !ok {
		return exit
	}
	if opts.Postgres.Name == "" {
		_, _ = fmt.Fprintln(stderr, "nanostack gen db: -name is required")
		return 2
	}
	opts.DatabaseURL = os.Getenv(EnvDatabaseURL)
	written, err := run(opts)
	for _, path := range written {
		_, _ = fmt.Fprintf(stdout, "nanostack gen db: wrote %s\n", path)
	}
	return gen.Report(stderr, "db", err)
}

func orDefault(s, def string) string {
	if s == "" {
		return def
	}
	return s
}
