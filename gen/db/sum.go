// Modules whose version decides the generated code.
const (
	genModule = "github.com/nanostack-dev/nanostack-framework/gen"
	dbModule  = "github.com/nanostack-dev/nanostack-framework/db"
)

// sumVersion changes when the format of nanogen.sum or the meaning of a
// line changes, so that an old file is a miss.
const sumVersion = "1"

// line is one line of nanogen.sum. An input has a key and a value, such as
// "image postgres:18-alpine" or "migration 000001_init.up.sql <sha256>"; an
// output has a path and a hash.
type line struct {
	kind string // "input" or "output"
	// key names an input: "format", "image", "schema", "generator gen",
	// "generator db" or "migration <file>". path names an output, relative
	// to <Out>/<Name>, slash-separated.
	key, path string
	// value is an input's value; hash is an output's sha256.
	value, hash string
}

// sumFile is the content of nanogen.sum.
type sumFile struct {
	inputs, outputs []line
}

func digest(data []byte) string {
	h := sha256.Sum256(data)
	return hex.EncodeToString(h[:])
}

// inputLines returns the inputs of a run, in a fixed order.
func inputLines(p project.Postgres, migrations []migration) []line {
	lines := []line{
		{kind: "input", key: "format", value: sumVersion},
		{kind: "input", key: "image", value: p.Image},
		{kind: "input", key: "schema", value: p.Schema},
		{kind: "input", key: "generator gen", value: moduleVersion(genModule)},
		{kind: "input", key: "generator db", value: moduleVersion(dbModule)},
	}
	for _, m := range migrations {
		lines = append(lines, line{kind: "input", key: "migration " + m.name, value: digest(m.data)})
	}
	return lines
}

// moduleVersion returns the version of a module in the running binary:
// its tag, "(devel)" in its own checkout, or "(replaced)" when a replace
// directive points it at a directory.
func moduleVersion(path string) string {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return "(unknown)"
	}
	for _, m := range append([]*debug.Module{&bi.Main}, bi.Deps...) {
		if m.Path != path {
			continue
		}
		if m.Replace != nil {
			return orDefault(m.Replace.Version, "(replaced)")
		}
		return orDefault(m.Version, "(devel)")
	}
	return "(devel)"
}

// bytes renders the file: the header, the inputs, then the outputs.
func (s sumFile) bytes() []byte {
	var b bytes.Buffer
	b.WriteString("# Code generated by nanostack gen db. DO NOT EDIT.\n")
	b.WriteString("# nanostack gen db reads no database while every input and every output below match.\n")
	for _, l := range s.inputs {
		_, _ = fmt.Fprintf(&b, "input %s %s\n", l.key, strconv.Quote(l.value))
	}
	for _, l := range s.outputs {
		_, _ = fmt.Fprintf(&b, "output %s %s\n", l.hash, l.path)
	}
	return b.Bytes()
}

// errNoSum reports a missing nanogen.sum.
var errNoSum = errors.New("no " + SumFile)

// readSum parses <out>/nanogen.sum.
func readSum(out string) (sumFile, error) {
	data, err := os.ReadFile(filepath.Join(out, SumFile))
	if errors.Is(err, os.ErrNotExist) {
		return sumFile{}, errNoSum
	}
	if err != nil {
		return sumFile{}, err
	}
	var s sumFile
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		text := sc.Text()
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		kind, rest, _ := strings.Cut(text, " ")
		switch kind {
		case "input":
			i := strings.LastIndex(rest, ` "`)
			if i < 0 {
				return sumFile{}, fmt.Errorf("line %d: an input needs a quoted value", n)
			}
			value, uqErr := strconv.Unquote(rest[i+1:])
			if uqErr != nil {
				return sumFile{}, fmt.Errorf("line %d: %w", n, uqErr)
			}
			s.inputs = append(s.inputs, line{kind: kind, key: rest[:i], value: value})
		case "output":
			hash, path, ok := strings.Cut(rest, " ")
			if !ok || len(hash) != sha256.Size*2 || !filepath.IsLocal(filepath.FromSlash(path)) {
				return sumFile{}, fmt.Errorf("line %d: an output is \"output <sha256> <path>\", "+
					"with a path under the directory of nanogen.sum", n)
			}
			s.outputs = append(s.outputs, line{kind: kind, path: path, hash: hash})
		default:
			return sumFile{}, fmt.Errorf("line %d: unknown line %q", n, kind)
		}
	}
	return s, sc.Err()
}

// cached returns the listed outputs and nanogen.sum when every input and
// every output matches it. Otherwise miss says what differs, the reason the
// run needs a database. An error is a file it cannot read.
func cached(l layout, inputs []line) (files []gen.File, miss string, err error) {
	sumPath := filepath.Join(l.out, SumFile)
	s, err := readSum(l.out)
	switch {
	case errors.Is(err, errNoSum):
		return nil, l.rel(sumPath) + " does not exist", nil
	case err != nil:
		miss = l.rel(sumPath) + " does not parse (" + err.Error() + ")"
		return nil, miss, nil //nolint:nilerr // a sum that does not parse is a miss, not a failure
	}
	if d := inputChange(s.inputs, inputs); d != "" {
		return nil, d + " since " + l.rel(sumPath), nil
	}
	listed := map[string]bool{sumPath: true}
	for _, o := range s.outputs {
		path := filepath.Join(l.out, filepath.FromSlash(o.path))
		listed[path] = true
		data, readErr := os.ReadFile(path)
		switch {
		case errors.Is(readErr, os.ErrNotExist):
			return nil, l.rel(path) + " is missing", nil
		case readErr != nil:
			return nil, "", &gen.Error{File: l.rel(path), Msg: readErr.Error(),
				Fix: "make the file readable", Err: gen.ErrEnvironment}
		case digest(data) != o.hash:
			return nil, l.rel(path) + " differs from " + l.rel(sumPath), nil
		}
		files = append(files, gen.File{Path: path, Data: data})
	}
	for _, path := range generatedUnder(l.out) {
		if !listed[path] {
			return nil, l.rel(path) + " is not in " + l.rel(sumPath), nil
		}
	}
	data, err := os.ReadFile(sumPath)
	if err != nil {
		return nil, "", &gen.Error{File: l.rel(sumPath), Msg: err.Error(), Fix: "make the file readable",
			Err: gen.ErrEnvironment}
	}
	return append(files, gen.File{Path: sumPath, Data: data}), "", nil
}

// inputChange names the first input that differs between the recorded and
// the current inputs, such as "migration 000002_x.up.sql changed"; "" when
// none does.
func inputChange(recorded, current []line) string {
	was := map[string]string{}
	for _, l := range recorded {
		was[l.key] = l.value
	}
	now := map[string]string{}
	for _, l := range current {
		now[l.key] = l.value
		old, ok := was[l.key]
		switch {
		case !ok:
			return l.key + " is new"
		case old != l.value && strings.HasPrefix(l.key, "migration "):
			return l.key + " changed"
		case old != l.value:
			return fmt.Sprintf("%s changed from %s to %s", l.key, old, l.value)
		}
	}
	gone := make([]string, 0, len(recorded))
	for _, l := range recorded {
		if _, ok := now[l.key]; !ok {
			gone = append(gone, l.key)
		}
	}
	if len(gone) > 0 {
		slices.Sort(gone)
		return gone[0] + " was removed"
	}
	return ""
}
