package genconfig

import (
	"fmt"
	"strings"
)

// renderEnvExample writes .env.example: one entry per setting, in declaration
// order, with its description.
//
// Environment variables override every config file, so a value copied into a
// .env file would silently mask the YAML profiles. Only required settings are
// therefore left uncommented, with an empty value that still counts as unset
// until someone fills it in. Settings with a default or marked optional are
// commented out, showing the default.
func renderEnvExample(m *model) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# Code generated by nano gen config from %s. DO NOT EDIT.\n", m.source)
	w("#\n")
	w("# Environment variables of %s.%s. Copy the file to .env and fill in the\n", m.pkgName, m.typeName)
	w("# required ones. Commented entries show the default, or are optional; an\n")
	w("# environment variable overrides the config files, so set one only to\n")
	w("# override them.\n")
	for _, s := range m.settings {
		w("\n")
		for line := range strings.SplitSeq(envComment(s), "\n") {
			w("# %s\n", line)
		}
		if s.required() {
			w("%s=\n", s.env)
			continue
		}
		w("# %s=%s\n", s.env, s.def)
	}
	return []byte(b.String())
}

// envComment describes s in one or two lines: the path, its status and type,
// then the description.
func envComment(s *setting) string {
	var status []string
	switch {
	case s.required():
		status = append(status, "required")
	case s.optional:
		status = append(status, "optional")
	}
	if s.secret() {
		status = append(status, "secret")
	}
	status = append(status, typeLabel(s))
	if s.rawCheck != "" {
		status = append(status, s.rawCheck)
	}
	head := s.path + " (" + strings.Join(status, "; ") + ")"
	if doc := strings.Join(strings.Fields(s.doc), " "); doc != "" {
		return head + "\n" + doc
	}
	return head
}
