package genconfig

import (
	"fmt"
	"strings"
)

// renderMarkdown writes the reference of every setting.
func renderMarkdown(m *model) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("<!-- Code generated by nano gen config from %s. DO NOT EDIT. -->\n\n", m.source)
	w("# Configuration reference\n\n")
	w("Settings of `%s` in package `%s`, bound by `%s`.\n\n", m.typeName, m.pkgPath, bindName(m))
	w("Each setting is read from its environment variable first, then from the secret store\n")
	w("(secret settings only), then from the YAML config files (later files win), then its\n")
	w("default. An empty value counts as unset. A setting without a default is required\n")
	w("unless it is optional. Secret settings are never read from config files and never\n")
	w("printed. Lists use commas in environment variables and YAML lists in files.\n\n")
	w("`nano gen config` checks every default against its type and validation, except\n")
	w("defaults of types that parse themselves (encoding.TextUnmarshaler, such as\n")
	w("slog.Level): those are checked when the service starts.\n\n")
	w("| Setting | Env | Type | Default | Required | Secret | Validation | Description |\n")
	w("|---|---|---|---|---|---|---|---|\n")
	for _, s := range m.settings {
		w("| `%s` | `%s` | %s | %s | %s | %s | %s | %s |\n",
			s.path, s.env, cell(typeLabel(s)), code(s.def), yesNo(s.required()), yesNo(s.secret()),
			code(s.rawCheck), cell(strings.Join(strings.Fields(s.doc), " ")))
	}
	return []byte(b.String())
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + cell(s) + "`"
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
