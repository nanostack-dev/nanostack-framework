// renderGo writes Bind, LogValue, String and GoString. Settings appear in
// declaration order and nothing depends on time or map order, so output is
// byte-for-byte reproducible.
func renderGo(m *model) ([]byte, error) {
	im := importset.New(m.pkgPath)
	im.Add("context", "context")
	im.Add("log/slog", "slog")
	im.Add(runtimePath, "nanoconf")
	// durationLiteral writes time.Second and friends, so "time" stays free
	// for the standard package even when a field type comes from another
	// package named time.
	im.Reserve("time", "time")

	var body strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&body, format, args...) }
	bind := bindName(m)
	w("// %s reads every %s setting from src, applies defaults, parses and\n", bind, m.typeName)
	w("// validates each value, and returns all issues together as a\n")
	w("// *nanoconf.Error. Precedence: environment variable, then the secret store\n")
	w("// (secret settings only), then config files, then the default.\n")
	w("func %s(ctx context.Context, src *nanoconf.Sources) (%s, error) {\n", bind, m.typeName)
	w("\tvar c %s\n", m.typeName)
	w("\tb := nanoconf.NewBinder(ctx, src)\n")
	for _, s := range m.settings {
		renderSetting(&body, im, s)
	}
	w("\tif err := b.Err(); err != nil {\n\t\treturn %s{}, err\n\t}\n\treturn c, nil\n}\n\n", m.typeName)

	w("// LogValue returns every setting as nested slog groups. Secrets show as\n")
	w("// %s and URLs lose their password, so the whole %s is safe to log.\n", secret.Redacted, m.typeName)
	w("func (c %s) LogValue() slog.Value {\n\treturn slog.GroupValue(\n", m.typeName)
	renderGroup(&body, im, m.root, 2)
	w("\t)\n}\n\n")
	w("// String returns the redacted LogValue on one line, as path=value pairs.\n")
	w("func (c %s) String() string { return nanoconf.Format(c.LogValue()) }\n\n", m.typeName)
	w("// GoString keeps %%#v as redacted as String.\n")
	w("func (c %s) GoString() string { return c.String() }\n", m.typeName)

	var file strings.Builder
	fmt.Fprintf(&file, "// Code generated by nanostack gen config from %s. DO NOT EDIT.\n\n", m.source)
	fmt.Fprintf(&file, "package %s\n\n", m.pkgName)
	im.Write(&file)
	file.WriteString(body.String())
	src, err := format.Source([]byte(file.String()))
	if err != nil {
		return nil, gen.Errorf("", 0, "report this nanostack gen config bug with the configuration struct",
			"format generated code: %v\n%s", err, file.String())
	}
	return src, nil
}

func bindName(m *model) string { return bindFuncName(m.typeName) }

// bindFuncName is Bind for the conventional Config type and Bind<Type>
// otherwise, so a package may hold more than one root.
func bindFuncName(typeName string) string {
	if typeName == "Config" {
		return "Bind"
	}
	return "Bind" + typeName
}

func renderSetting(b *strings.Builder, im *importset.Set, s *setting) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	comment := s.path
	if line, _, _ := strings.Cut(s.doc, "\n"); line != "" {
		comment += ": " + line
	}
	w("\n\t// %s\n\t{\n", comment)
	key := []string{"Path: " + strconv.Quote(s.path), "Env: " + strconv.Quote(s.env)}
	if s.defEnv != "" {
		key = append(key, "DefaultEnv: "+strconv.Quote(s.defEnv))
	}
	if s.def != "" {
		key = append(key, "Default: "+strconv.Quote(s.def))
	}
	if s.optional {
		key = append(key, "Optional: true")
	}
	if s.secret() {
		key = append(key, "Secret: true")
	}
	w("\t\tk := nanoconf.Key{%s}\n", strings.Join(key, ", "))
	bindFn := "Scalar"
	if s.list {
		bindFn = "List"
	}
	call := fmt.Sprintf("nanoconf.%s(b, k, %s)", bindFn, parseFunc(im, s))
	if len(s.checks) == 0 {
		w("\t\tc.%s, _ = %s\n\t}\n", s.goExpr, call)
		return
	}
	w("\t\tif v, ok := %s; ok {\n", call)
	w("\t\t\tc.%s = v\n", s.goExpr)
	if s.list {
		w("\t\t\tfor i, e := range v {\n")
		for _, c := range s.checks {
			w("\t\t\t\t%s\n", checkCall(im, c, "k.Elem(i)", "e"))
		}
		w("\t\t\t}\n")
	} else {
		for _, c := range s.checks {
			w("\t\t\t%s\n", checkCall(im, c, "k", "v"))
		}
	}
	w("\t\t}\n\t}\n")
}

// parseFunc names the core/config parse helper for the setting's element type.
func parseFunc(im *importset.Set, s *setting) string {
	generic := func(name string) string {
		return "nanoconf." + name + "[" + types.TypeString(s.elemType, im.Qualifier) + "]"
	}
	switch s.kind {
	case kindString:
		return generic("ParseString")
	case kindBool:
		return generic("ParseBool")
	case kindInt:
		return generic("ParseInt")
	case kindUint:
		return generic("ParseUint")
	case kindFloat:
		return generic("ParseFloat")
	case kindText:
		return generic("ParseText")
	case kindDuration:
		return "nanoconf.ParseDuration"
	case kindURL:
		return "nanoconf.ParseURL"
	case kindSecret:
		return "nanoconf.ParseSecret"
	}
	panic("unreachable: unclassified setting " + s.path)
}

func checkCall(im *importset.Set, c check, key, val string) string {
	for _, a := range c.args {
		if strings.Contains(a, "time.") {
			im.Add("time", "time")
		}
	}
	fn := map[string]string{"between": "Between", "min": "Min", "max": "Max", "oneof": "OneOf", "scheme": "Scheme"}[c.rule]
	return fmt.Sprintf("nanoconf.%s(b, %s, %s, %s)", fn, key, val, strings.Join(c.args, ", "))
}

func renderGroup(b *strings.Builder, im *importset.Set, g *group, depth int) {
	indent := strings.Repeat("\t", depth)
	for _, n := range g.children {
		if n.group != nil {
			fmt.Fprintf(b, "%sslog.Group(%q,\n", indent, n.group.name)
			renderGroup(b, im, n.group, depth+1)
			fmt.Fprintf(b, "%s),\n", indent)
			continue
		}
		fmt.Fprintf(b, "%s%s,\n", indent, attr(im, n.setting))
	}
}

// attr renders the slog attribute of one setting, redacting secrets and URL
// credentials through core/secret.
func attr(im *importset.Set, s *setting) string {
	x := "c." + s.goExpr
	name := strconv.Quote(s.name)
	if s.list {
		if s.kind == kindURL {
			return "slog.Any(" + name + ", " + im.Add(secretPath, "secret") + ".RedactURLs(" + x + "))"
		}
		return "slog.Any(" + name + ", " + x + ")"
	}
	conv := func(basic types.BasicKind, fn, goType string) string {
		if types.Identical(s.elemType, types.Typ[basic]) {
			return "slog." + fn + "(" + name + ", " + x + ")"
		}
		return "slog." + fn + "(" + name + ", " + goType + "(" + x + "))"
	}
	switch s.kind {
	case kindString:
		return conv(types.String, "String", "string")
	case kindBool:
		return conv(types.Bool, "Bool", "bool")
	case kindInt:
		if types.Identical(s.elemType, types.Typ[types.Int]) {
			return "slog.Int(" + name + ", " + x + ")"
		}
		return conv(types.Int64, "Int64", "int64")
	case kindUint:
		return conv(types.Uint64, "Uint64", "uint64")
	case kindFloat:
		return conv(types.Float64, "Float64", "float64")
	case kindDuration:
		return "slog.Duration(" + name + ", " + x + ")"
	case kindURL:
		return "slog.String(" + name + ", " + im.Add(secretPath, "secret") + ".RedactURL(" + x + "))"
	case kindSecret:
		return "slog.String(" + name + ", " + x + ".String())"
	default:
		return "slog.Any(" + name + ", " + x + ")"
	}
}
