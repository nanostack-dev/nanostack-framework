const specHeader = "// Code generated by nano gen api from openapi.yaml. DO NOT EDIT.\n\n"

// The server is oapi-codegen's command output byte for byte, after nano's
// header. testdata/upstream/api.gen.go is that output for the spec of
// http/nanohttp/internal/example; oapi-codegen.yaml next to it says how to
// regenerate it.
func TestServerMatchesTheCommand(t *testing.T) {
	dir := filepath.Join("testdata", "upstream")
	want, err := os.ReadFile(filepath.Join(dir, "api.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	files, err := Generate(Options{Spec: filepath.Join(dir, "openapi.yaml"), Server: project.Package{Dir: dir}})
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 2 || files[0].Path != filepath.Join(dir, DefaultServerFile) ||
		files[1].Path != filepath.Join(dir, HandlersFile) {
		t.Fatalf("files = %v", paths(files))
	}
	got := files[0].Data
	body, ok := bytes.CutPrefix(got, []byte(specHeader))
	if !ok {
		t.Fatalf("the output does not start with nano's header:\n%s", firstLines(got, 3))
	}
	if !bytes.Equal(body, want) {
		t.Errorf("the output differs from oapi-codegen's command after the header:\n%s", firstDiff(body, want))
	}
	// The header sits above //go:build go1.22 and keeps the file gofmt-clean.
	if formatted, fmtErr := format.Source(got); fmtErr != nil || !bytes.Equal(formatted, got) {
		t.Errorf("the output is not gofmt-clean (err %v)", fmtErr)
	}
}

// PlainTypes gives the client that anchor's scripts/client-spec.sh gives:
// testdata/plaintypes/openapi.client.yaml is the script's output.
func TestPlainTypesMatchesClientSpecScript(t *testing.T) {
	dir := filepath.Join("testdata", "plaintypes")
	out := t.TempDir()
	plain := generateOne(t, Options{Spec: filepath.Join(dir, "openapi.yaml"),
		Clients: []project.Client{{Dir: out, Package: "client", PlainTypes: true}}})
	script := generateOne(t, Options{Spec: filepath.Join(dir, "openapi.client.yaml"),
		Clients: []project.Client{{Dir: out, Package: "client"}}})
	if !bytes.Equal(dropFirstLine(plain), dropFirstLine(script)) {
		t.Errorf("PlainTypes and client-spec.sh give different clients:\n%s",
			firstDiff(dropFirstLine(plain), dropFirstLine(script)))
	}
	hinted := generateOne(t, Options{Spec: filepath.Join(dir, "openapi.yaml"),
		Clients: []project.Client{{Dir: out, Package: "client"}}})
	for _, hint := range []string{"nullable.Nullable[string]", "role.SortField", "search.Pagination", "[]uuid.UUID", "role.Owner"} {
		if !bytes.Contains(hinted, []byte(hint)) {
			t.Errorf("the client without PlainTypes lacks %s; the fixture no longer exercises it", hint)
		}
		if bytes.Contains(plain, []byte(hint)) {
			t.Errorf("the PlainTypes client still uses %s", hint)
		}
	}
}

// The server keeps its hints when a client of the same run drops them: each
// output loads the spec again.
func TestPlainTypesDoesNotReachTheServer(t *testing.T) {
	server := filepath.Join(t.TempDir(), "api")
	if err := os.Mkdir(server, 0o750); err != nil {
		t.Fatal(err)
	}
	files, err := Generate(Options{
		Spec:    filepath.Join("testdata", "plaintypes", "openapi.yaml"),
		Server:  project.Package{Dir: server},
		Clients: []project.Client{{Dir: filepath.Join(server, "client"), Package: "client", PlainTypes: true}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 3 {
		t.Fatalf("files = %v", paths(files))
	}
	if !bytes.Contains(files[0].Data, []byte("nullable.Nullable[string]")) {
		t.Error("the server lost its nullable.Nullable hint")
	}
	if bytes.Contains(files[2].Data, []byte("nullable.Nullable[string]")) {
		t.Error("the client kept the nullable.Nullable hint")
	}
	if !bytes.Contains(files[2].Data, []byte("package client\n")) {
		t.Errorf("client package clause missing:\n%s", firstLines(files[2].Data, 6))
	}
}

// Every error path names its fix.
func TestErrorsNameTheirFix(t *testing.T) {
	tmp := t.TempDir()
	twoPkgs := filepath.Join(tmp, "two")
	mustWrite(t, filepath.Join(twoPkgs, "a.go"), "package a\n")
	mustWrite(t, filepath.Join(twoPkgs, "b.go"), "package b\n")
	badName := filepath.Join(tmp, "not-a-name")
	if err := os.MkdirAll(badName, 0o750); err != nil {
		t.Fatal(err)
	}
	invalid := filepath.Join(tmp, "invalid.yaml")
	mustWrite(
		t,
		invalid,
		"openapi: 3.0.3\ninfo: {title: x, version: \"1\"}\npaths:\n  /x:\n    get: [not, an, operation]\n",
	)
	spec := filepath.Join("testdata", "upstream", "openapi.yaml")
	server := project.Package{Dir: filepath.Join("testdata", "upstream")}

	tests := []struct {
		name string
		opts Options
		want string
	}{
		{"no spec", Options{Server: server}, "no spec"},
		{"nothing to generate", Options{Spec: spec}, "nothing to generate"},
		{"missing spec", Options{Spec: filepath.Join(tmp, "nope.yaml"), Server: server}, "does not exist"},
		{"invalid spec", Options{Spec: invalid, Server: server}, "load the spec"},
		{"missing server dir", Options{Spec: spec, Server: project.Package{Dir: filepath.Join(tmp, "nope")}},
			"does not exist"},
		{"two packages", Options{Spec: spec, Server: project.Package{Dir: twoPkgs}}, "several packages: a, b"},
		{"dir name is no package", Options{Spec: spec, Server: project.Package{Dir: badName}},
			"not a package name"},
		{"client package", Options{Spec: spec, Clients: []project.Client{{Dir: tmp, Package: "go"}}},
			"not a Go identifier"},
		{"client dir", Options{Spec: spec, Clients: []project.Client{{Package: "client"}}}, "has no Dir"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Generate(tt.opts)
			problems := gentest.Problems(t, err)
			if len(problems) != 1 || !strings.Contains(problems[0].Msg, tt.want) {
				t.Errorf("problems = %v, want one with %q", problems, tt.want)
			}
			if gentest.Environment(err) {
				t.Errorf("a source problem is classed as the environment: %v", err)
			}
		})
	}
}

// A remote $ref is refused before any request: oapi-codegen's command would
// fetch it.
func TestRemoteRefIsRefused(t *testing.T) {
	var requests atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		requests.Add(1)
		_, _ = w.Write([]byte("B: {type: string}\n"))
	}))
	t.Cleanup(srv.Close)
	remote := filepath.Join(t.TempDir(), "remote.yaml")
	mustWrite(t, remote, "openapi: 3.0.3\ninfo: {title: x, version: \"1\"}\npaths: {}\ncomponents:\n"+
		"  schemas:\n    A: {$ref: '"+srv.URL+"/schemas.yaml#/B'}\n")
	_, err := Generate(Options{Spec: remote, Clients: []project.Client{{Dir: t.TempDir(), Package: "client"}}})
	problems := gentest.Problems(t, err)
	if len(problems) != 1 || !strings.Contains(problems[0].Msg, "refusing to resolve remote reference") ||
		problems[0].Fix != loadFix {
		t.Errorf("problems = %v, want one refused remote reference with the load fix", problems)
	}
	if n := requests.Load(); n != 0 {
		t.Errorf("the step fetched the remote reference %d times", n)
	}
}

func TestMainCommand(t *testing.T) {
	spec := filepath.Join("testdata", "upstream", "openapi.yaml")
	t.Run("bad usage", func(t *testing.T) {
		for _, args := range [][]string{
			{},
			{"-spec", spec},
			{"-spec", spec, "-client", t.TempDir()},
			{"-nope"},
		} {
			var stderr bytes.Buffer
			if code := Main(args, &bytes.Buffer{}, &stderr); code != 2 {
				t.Errorf("Main(%q) = %d, want 2; stderr: %s", args, code, stderr.String())
			}
		}
	})
	t.Run("writes, then checks", func(t *testing.T) {
		dir := filepath.Join(t.TempDir(), "example")
		args := []string{"-spec", spec, "-dir", dir, "-client", filepath.Join(dir, "client"),
			"-client-package", "client", "-plain-types"}
		var stdout, stderr bytes.Buffer
		if err := os.Mkdir(dir, 0o750); err != nil {
			t.Fatal(err)
		}
		if code := Main(append(args, "-check"), &stdout, &stderr); code != 1 {
			t.Errorf("-check on missing files = %d, want 1; stderr: %s", code, stderr.String())
		}
		stderr.Reset()
		if code := Main(args, &stdout, &stderr); code != 0 {
			t.Fatalf("Main = %d; stderr: %s", code, stderr.String())
		}
		if !strings.Contains(stdout.String(), "wrote "+filepath.Join(dir, "api.gen.go")) ||
			!strings.Contains(stdout.String(), "wrote "+filepath.Join(dir, "client", "client.gen.go")) {
			t.Errorf("stdout = %s", stdout.String())
		}
		if code := Main(append(args, "-check"), &stdout, &stderr); code != 0 {
			t.Errorf("-check after a run = %d; stderr: %s", code, stderr.String())
		}
	})
	t.Run("another oapi-codegen exits 3", func(t *testing.T) {
		fakeBuildInfo(t, "v2.9.0", nil)
		var stderr bytes.Buffer
		code := Main([]string{"-spec", spec, "-dir", t.TempDir(), "-check"}, &bytes.Buffer{}, &stderr)
		if code != 3 {
			t.Errorf("Main = %d, want 3", code)
		}
		want := "nano gen api: oapi-codegen v2.9.0 resolved; nano templates are pinned to v2.8.2\n" +
			"  fix: go get github.com/oapi-codegen/oapi-codegen/v2@v2.8.2\n"
		if stderr.String() != want {
			t.Errorf("stderr = %q, want %q", stderr.String(), want)
		}
	})
}

func generateOne(t *testing.T, opts Options) []byte {
	t.Helper()
	files, err := Generate(opts)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v", paths(files))
	}
	return files[0].Data
}

func paths(files []gen.File) []string {
	out := make([]string, len(files))
	for i, f := range files {
		out[i] = f.Path
	}
	return out
}

func mustWrite(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}

func dropFirstLine(b []byte) []byte {
	_, rest, _ := bytes.Cut(b, []byte("\n"))
	return rest
}

func firstLines(b []byte, n int) []byte {
	lines := bytes.SplitAfterN(b, []byte("\n"), n+1)
	return bytes.Join(lines[:min(n, len(lines))], nil)
}

// firstDiff returns the first line where got and want differ.
func firstDiff(got, want []byte) string {
	g, w := strings.Split(string(got), "\n"), strings.Split(string(want), "\n")
	for i := range max(len(g), len(w)) {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl != wl {
			return "line " + strconv.Itoa(i+1) + ":\n  got:  " + gl + "\n  want: " + wl
		}
	}
	return "(no line differs)"
}
