// Package genapi implements nano gen api: it runs oapi-codegen v2.8.2
// in-process on an OpenAPI document and writes the server package and each
// Go client.
//
// The server is the HTTP boundary of the framework: models and a strict
// server on net/http's ServeMux (std-http-server), with the strict template
// and the union template replaced by the overrides in package
// http/nanohttp/oapitemplates. The overrides decode bodies strictly through
// nanohttp, run the validators nano gen validate writes, and send every
// error through problem as RFC 9457 application/problem+json. A client holds
// models and a client type in one file.
//
// oapi-codegen is a library of the gen module, so nano and the templates
// resolve one version. A binary built with any other version fails with an
// environment error (exit 3), because the templates are cut from v2.8.2.
//
// Each output starts with "Code generated by nano gen api from <spec>. DO
// NOT EDIT.", then holds oapi-codegen's output unchanged: byte for byte what
// `go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.2`
// writes for the same configuration.
//
// The api step reads only the spec; it loads no Go package, so its Options
// have no Overlay. oapi-codegen keeps its configuration in package state, so
// generations run one at a time.
package genapi

import (
	"errors"
	"flag"
	"fmt"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"sync"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"

	"github.com/nanostack-dev/nanostack-framework/core/nano/project"
	"github.com/nanostack-dev/nanostack-framework/gen"
	"github.com/nanostack-dev/nanostack-framework/http/nanohttp/oapitemplates"
)

// Default file names.
const (
	DefaultServerFile = "api.gen.go"
	DefaultClientFile = "client.gen.go"
)

// Packages the generated server imports through the template override.
const (
	nanohttpPackage = "github.com/nanostack-dev/nanostack-framework/http/nanohttp"
	problemPackage  = "github.com/nanostack-dev/nanostack-framework/http/problem"
)

// Options configures one run. Paths are absolute, or relative to the working
// directory.
type Options struct {
	// Spec is the OpenAPI 3.0 or 3.1 document.
	Spec string
	// Server is the server package. A zero Dir generates no server.
	Server project.Package
	// Clients are generated after the server, in order.
	Clients []project.Client
	// Check makes Run compare instead of writing.
	Check bool
}

// generateMu serializes codegen.Generate, which keeps its configuration in
// package state.
var generateMu sync.Mutex //nolint:gochecknoglobals // guards oapi-codegen's package state.

// Generate renders the server and the clients in memory. It fails with an
// environment error when the binary resolved another oapi-codegen than
// v2.8.2.
func Generate(opts Options) ([]gen.File, error) {
	version, err := pinnedVersion()
	if err != nil {
		return nil, err
	}
	if opts.Spec == "" {
		return nil, gen.Errorf("", 0, "pass the OpenAPI document", "no spec")
	}
	if opts.Server.Dir == "" && len(opts.Clients) == 0 {
		return nil, gen.Errorf("", 0, "name a server directory, a client, or both",
			"nothing to generate from %s", opts.Spec)
	}
	var files []gen.File
	if opts.Server.Dir != "" {
		pkg, pkgErr := packageName(opts.Server.Dir)
		if pkgErr != nil {
			return nil, pkgErr
		}
		f, renderErr := render(opts.Spec, opts.Server.Dir, orDefault(opts.Server.File, DefaultServerFile), version,
			serverConfig(pkg), false)
		if renderErr != nil {
			return nil, renderErr
		}
		files = append(files, f)
	}
	for i, c := range opts.Clients {
		if !token.IsIdentifier(c.Package) {
			return nil, gen.Errorf("", 0, "set the client's Package to a Go package name",
				"client %d (%s): package %q is not a Go identifier", i, c.Dir, c.Package)
		}
		if c.Dir == "" {
			return nil, gen.Errorf("", 0, "set the client's Dir", "client %d (package %s) has no Dir", i, c.Package)
		}
		f, renderErr := render(opts.Spec, c.Dir, orDefault(c.File, DefaultClientFile), version,
			clientConfig(c.Package), c.PlainTypes)
		if renderErr != nil {
			return nil, renderErr
		}
		files = append(files, f)
	}
	return files, nil
}

// Run generates and writes the files that changed. With Options.Check it
// writes nothing and returns an error wrapping gen.ErrStale when a file is
// missing or differs.
func Run(opts Options) error {
	_, err := run(opts)
	return err
}

func run(opts Options) ([]string, error) {
	files, err := Generate(opts)
	if err != nil {
		return nil, err
	}
	return gen.Sync("api", files, opts.Check)
}

// Main runs `nano gen api -spec file [-dir dir] [-out file] [-client dir
// -client-package name [-client-out file] [-plain-types]] [-check]` and
// returns the exit code: 0 on success, 1 on a source error or stale output,
// 2 on bad flags, 3 when the environment fails (a file cannot be read or
// written, or the binary resolved another oapi-codegen). It is a
// gen.Command. The pipeline runs the same generator from nanogen/project.go,
// with every client the declaration lists.
func Main(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("nano gen api", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var opts Options
	var client project.Client
	fs.StringVar(&opts.Spec, "spec", "", "OpenAPI 3.0 or 3.1 document")
	fs.StringVar(&opts.Server.Dir, "dir", "", "directory of the server package; empty generates no server")
	fs.StringVar(&opts.Server.File, "out", DefaultServerFile, "server file name inside -dir")
	fs.StringVar(&client.Dir, "client", "", "directory of a Go client to generate")
	fs.StringVar(&client.Package, "client-package", "", "package name of the client")
	fs.StringVar(&client.File, "client-out", DefaultClientFile, "client file name inside -client")
	fs.BoolVar(&client.PlainTypes, "plain-types", false, "drop the server's x-go-type hints from the client")
	fs.BoolVar(&opts.Check, "check", false, "write nothing; exit 1 if a generated file is stale")
	if exit, ok := gen.ParseFlags(fs, args); !ok {
		return exit
	}
	switch {
	case opts.Spec == "":
		_, _ = fmt.Fprintln(stderr, "nano gen api: -spec is required")
		return 2
	case opts.Server.Dir == "" && client.Dir == "":
		_, _ = fmt.Fprintln(stderr, "nano gen api: pass -dir, -client, or both")
		return 2
	case client.Dir != "" && client.Package == "":
		_, _ = fmt.Fprintln(stderr, "nano gen api: -client needs -client-package")
		return 2
	}
	if client.Dir != "" {
		opts.Clients = []project.Client{client}
	}
	written, err := run(opts)
	for _, path := range written {
		_, _ = fmt.Fprintf(stdout, "nano gen api: wrote %s\n", path)
	}
	return gen.Report(stderr, "api", err)
}

// serverConfig is the framework's server configuration: models and a strict
// server on net/http's ServeMux, through the template overrides.
func serverConfig(pkg string) codegen.Configuration {
	return codegen.Configuration{
		PackageName: pkg,
		Generate:    codegen.GenerateOptions{Models: true, StdHTTPServer: true, Strict: true},
		AdditionalImports: []codegen.AdditionalImport{
			{Package: nanohttpPackage},
			{Package: problemPackage},
		},
		OutputOptions: codegen.OutputOptions{UserTemplates: oapitemplates.UserTemplates()},
	}
}

// clientConfig is a client with its models, in one file.
func clientConfig(pkg string) codegen.Configuration {
	return codegen.Configuration{
		PackageName: pkg,
		Generate:    codegen.GenerateOptions{Models: true, Client: true},
	}
}

// render loads the spec, applies PlainTypes when asked, and runs
// oapi-codegen. Each call loads the spec again: codegen.Generate may change
// the document, and a client's PlainTypes must not reach the server.
func render(spec, dir, file, version string, cfg codegen.Configuration, plain bool) (gen.File, error) {
	doc, err := loadSpec(spec)
	if err != nil {
		return gen.File{}, err
	}
	if plain {
		plainTypes(doc)
	}
	cfg.NoVCSVersionOverride = &version
	cfg = cfg.UpdateDefaults()
	if err = cfg.Validate(); err != nil {
		return gen.File{}, gen.Errorf("", 0, "report it: the api step built an invalid oapi-codegen configuration",
			"oapi-codegen configuration: %v", err)
	}
	generateMu.Lock()
	code, err := codegen.Generate(doc, cfg)
	generateMu.Unlock()
	if err != nil {
		return gen.File{}, gen.Errorf(spec, 0, "change the spec so oapi-codegen "+version+" accepts it",
			"oapi-codegen: %v", err)
	}
	src, err := withHeader(code, version, relativeTo(dir, spec))
	if err != nil {
		return gen.File{}, err
	}
	return gen.File{Path: filepath.Join(dir, file), Data: src}, nil
}

// loadFix is the fix of a spec that does not load.
const loadFix = "fix the spec so oapi-codegen can load it; a remote $ref is not followed: " +
	"copy its schema into a local file"

// loadSpec loads the document as oapi-codegen's command does, with element
// origins, but refuses every remote reference: generation reads only files.
func loadSpec(spec string) (*openapi3.T, error) {
	if _, err := os.Stat(spec); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, gen.Errorf(spec, 0, "pass the path of the OpenAPI document", "the spec does not exist")
		}
		return nil, &gen.Error{File: spec, Msg: err.Error(), Fix: "make the spec readable", Err: gen.ErrEnvironment}
	}
	doc, err := util.LoadSwaggerWithOverlay(spec, util.LoadSwaggerWithOverlayOpts{
		Strict:              true,
		AllowRemoteRefsFrom: []string{},
	})
	if err != nil {
		return nil, gen.Errorf(spec, 0, loadFix, "load the spec: %v", err)
	}
	return doc, nil
}

// upstreamHeader matches the header line oapi-codegen writes. It names the
// module of the running binary, which is nano's, not oapi-codegen's.
//
//nolint:gochecknoglobals // compiled once.
var upstreamHeader = regexp.MustCompile(`(?m)^// Code generated by .* DO NOT EDIT\.$`)

// withHeader prepends nano's header and rewrites oapi-codegen's own header
// line to what oapi-codegen's command writes, so the rest of the file is
// what that command produces.
func withHeader(code, version, spec string) ([]byte, error) {
	loc := upstreamHeader.FindStringIndex(code)
	if loc == nil {
		return nil, gen.Errorf("", 0, "report it: nano gen api expects oapi-codegen "+version+"'s header",
			"oapi-codegen output has no \"Code generated by\" line")
	}
	var b strings.Builder
	b.WriteString("// Code generated by nano gen api from " + spec + ". DO NOT EDIT.\n\n")
	b.WriteString(code[:loc[0]])
	b.WriteString("// Code generated by " + modulePath + " version " + version + " DO NOT EDIT.")
	b.WriteString(code[loc[1]:])
	return []byte(b.String()), nil
}

// packageName returns the package that the Go files in dir declare, or the
// name of dir when it has none.
func packageName(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return "", gen.Errorf(dir, 0, "create the server package directory, or fix its path",
				"the server directory does not exist")
		}
		return "", &gen.Error{File: dir, Msg: err.Error(), Fix: "make the directory readable", Err: gen.ErrEnvironment}
	}
	names := map[string]bool{}
	fset := token.NewFileSet()
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, parseErr := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.PackageClauseOnly)
		if parseErr != nil {
			continue // a broken file names no package; another may
		}
		names[f.Name.Name] = true
	}
	switch len(names) {
	case 1:
		for name := range names {
			return name, nil
		}
	case 0:
		abs, absErr := filepath.Abs(dir)
		if absErr == nil && token.IsIdentifier(filepath.Base(abs)) {
			return filepath.Base(abs), nil
		}
		return "", gen.Errorf(dir, 0, "add a Go file with the package clause to the server directory",
			"the server directory has no Go file and its name is not a package name")
	}
	found := make([]string, 0, len(names))
	for name := range names {
		found = append(found, name)
	}
	slices.Sort(found)
	return "", gen.Errorf(dir, 0, "keep one package in the server directory",
		"the Go files declare several packages: %s", strings.Join(found, ", "))
}

// relativeTo returns path relative to dir, slash-separated, so the header is
// the same on every machine.
func relativeTo(dir, path string) string {
	absPath, errPath := filepath.Abs(path)
	absDir, errDir := filepath.Abs(dir)
	if errPath != nil || errDir != nil {
		return filepath.ToSlash(path)
	}
	rel, err := filepath.Rel(absDir, absPath)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}

func orDefault(s, def string) string {
	if s == "" {
		return def
	}
	return s
}
