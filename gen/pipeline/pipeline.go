// Package pipeline implements `nano gen` without a generator name: it runs
// every generation step of a module, in a fixed order, from one command.
//
//	go tool nano gen                # run every step, write what changed
//	go tool nano gen -check         # write nothing; exit 1 on a stale, missing or orphaned file
//	go tool nano gen -check -diff   # also print the first 20 lines of each diff
//	go tool nano gen -only config   # these steps, still in pipeline order (-skip is the inverse)
//	go tool nano gen -list          # print the plan: step, package, inputs, outputs
//	go tool nano gen -json          # one JSON event per line
//
// The inputs that cannot be discovered come from nanogen/project.go, a
// project.Project literal that nano reads from source (package
// core/nano/project). The rest is discovered by parsing, so discovery works
// on a tree that does not compile:
//
//   - errors: each package with a //nano:errors declaration;
//   - config and wire: each package with a //go:build nanogen file that calls
//     nano.Manifest. config reads that package's Config; wire writes
//     wire.gen.go into the package;
//   - api: the Project's API, when it declares one: oapi-codegen writes the
//     server and each client (package gen/api);
//   - validate: the server of the Project's API.
//
// The steps run one after another in the order api, validate, errors,
// config, wire, so each loads the fresh output of the steps before it. Without
// -check each step writes before the next loads. With -check nothing is
// written: the fresh outputs reach later loads as a go/packages overlay. In
// both modes an existing output of a later step is replaced, in every load,
// by a stub whose function bodies panic, so a stale later output cannot
// break an earlier step.
//
// A failed step skips the steps that need it, and the other steps still
// run, so one run reports every problem. api, validate and config read
// nanogen/project.go: a declaration with an error skips them, and wire. A
// validation gap fails the run but skips nothing: its file is still written.
//
// Every file a step writes starts with "Code generated by nano gen <step>".
// A file under the directory nano runs on with that header, for a step that
// ran, that the run did not produce is an orphan: the run deletes it, and
// -check fails on it. A step with nothing to run on has run, such as errors
// without a catalogue, or api and validate in a declaration without an
// API; a skipped step has not, and neither api nor validate has run without
// nanogen/project.go.
//
// Two guards keep generation in the pipeline: an unknown //nano: directive
// and a //go:generate line that runs nano gen or oapi-codegen are errors at
// their line.
//
// Exit codes: 0 success, 1 a source error, a validation gap or a stale,
// missing or orphaned file, 2 bad usage, 3 an environment failure. ADR 0023
// records the design.
package pipeline

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/nanostack-dev/nanostack-framework/core/nano/project"
	"github.com/nanostack-dev/nanostack-framework/gen"
)

// Options configures one run.
type Options struct {
	// Dir is the directory the run covers: nanogen/project.go sits in it,
	// every path in the project is relative to it, and discovery and the
	// orphan scan walk it. Default: the root of the module that holds the
	// working directory.
	Dir string
	// Check writes nothing and reports every stale, missing and orphaned
	// file.
	Check bool
	// Diff adds the first lines of each stale file's diff to its event.
	// It needs Check.
	Diff bool
	// Only runs these steps, in pipeline order. Skip runs every step but
	// these. At most one of them is set.
	Only, Skip []string
}

// Event levels.
const (
	LevelWrote   = "wrote"   // a file was written
	LevelDeleted = "deleted" // an orphan was deleted
	LevelStale   = "stale"   // -check: a file differs from what its step produces
	LevelMissing = "missing" // -check: a file the step produces does not exist
	LevelOrphan  = "orphan"  // -check: a generated file that no step produces
	LevelSkipped = "skipped" // a step did not run because a step it needs failed
	LevelError   = "error"   // a problem, with its fix
	LevelPlan    = "plan"    // -list: one unit of the plan
)

// StepPlan is the Event step of a problem found before any step runs: in
// nanogen/project.go, in discovery, or by a guard.
const StepPlan = "plan"

// Event is one result of a run, and one line of -json output.
type Event struct {
	Step  string `json:"step"`
	Level string `json:"level"`
	// File is relative to Options.Dir, slash-separated. Empty when no file
	// applies.
	File string `json:"file,omitempty"`
	Line int    `json:"line,omitempty"`
	Msg  string `json:"msg"`
	Fix  string `json:"fix,omitempty"`
	// Diff holds the first lines of a stale file's diff, with -diff.
	Diff []string `json:"diff,omitempty"`
	// Inputs and Outputs describe a unit of the plan, with -list.
	Inputs  []string `json:"inputs,omitempty"`
	Outputs []string `json:"outputs,omitempty"`

	env bool // the problem wraps gen.ErrEnvironment
}

// Result is the outcome of a run: its events, file results first, and the
// exit code.
type Result struct {
	Events []Event
	Exit   int
}

// step is one generation step of the pipeline.
type step struct {
	name  string
	needs []string // the earlier steps whose failure skips this one
	// project is true when the step reads nanogen/project.go: a declaration
	// that cannot be read skips it, and the steps that need it.
	project bool
	// run generates one unit. An error stops the step and skips the steps
	// that need it.
	run func(r *runner, u *unit, overlay map[string][]byte) (output, error)
	// base is the directory a generator's relative error paths start from.
	base func(r *runner, u *unit) string
}

// steps is the fixed order. The db, mapper and lint steps of the design join
// it as they land.
var steps = []step{ //nolint:gochecknoglobals // read-only table.
	{name: "api", project: true, run: runAPI, base: func(r *runner, _ *unit) string { return r.wd }},
	{name: "validate", needs: []string{"api"}, project: true, run: runValidate,
		base: func(r *runner, _ *unit) string { return r.wd }},
	{name: "errors", run: runErrors, base: unitBase},
	{name: "config", needs: []string{"validate", "errors"}, project: true, run: runConfig, base: unitBase},
	{name: "wire", needs: []string{"config"}, run: runWire, base: func(r *runner, _ *unit) string { return r.root }},
}

// StepNames returns the names of the steps, in pipeline order.
func StepNames() []string {
	names := make([]string, len(steps))
	for i, s := range steps {
		names[i] = s.name
	}
	return names
}

func unitBase(_ *runner, u *unit) string { return u.dir }

// output is what one unit generated.
type output struct {
	files []gen.File
	// gaps are problems that fail the run but leave files that later
	// steps can use, such as a validation gap.
	gaps error
}

// unit is one run of one step on one package.
type unit struct {
	step    *step
	dir     string   // absolute package directory
	inputs  []string // absolute
	outputs []string // absolute, the files the step writes
}

// runner holds the state of one run.
type runner struct {
	opts Options
	root string // absolute Options.Dir
	wd   string
	proj project.Project
	// declared is true when nanogen/project.go exists and was read.
	declared bool
	found    *discovery
	units    []*unit
	fresh    map[string][]byte // outputs of this run, by absolute path
	failed   map[string]bool   // steps with a unit that failed
	ran      map[string]bool   // steps that ran
	files    []Event           // wrote, deleted, stale, missing, orphan
	notes    []Event           // skipped and error
	planned  map[string]bool   // every output of every unit, for the orphan scan
}

// Run runs the pipeline and returns its events and exit code. It writes and
// deletes files only without Options.Check.
func Run(opts Options) Result {
	r := &runner{opts: opts, fresh: map[string][]byte{}, failed: map[string]bool{}, ran: map[string]bool{}}
	if res, ok := r.setup(); !ok {
		return res
	}
	for i, u := range r.units {
		r.runUnit(i, u)
	}
	r.scanOrphans()
	return r.result()
}

// List returns the plan of a run without running it: one LevelPlan event per
// unit, after any problem the plan has.
func List(opts Options) Result {
	r := &runner{opts: opts, fresh: map[string][]byte{}, failed: map[string]bool{}, ran: map[string]bool{}}
	if res, ok := r.setup(); !ok {
		return res
	}
	for _, u := range r.units {
		r.files = append(r.files, Event{
			Step:    u.step.name,
			Level:   LevelPlan,
			File:    r.rel(u.dir),
			Msg:     u.step.name + " " + r.rel(u.dir),
			Inputs:  r.rels(u.inputs),
			Outputs: r.rels(u.outputs),
		})
	}
	return r.result()
}

// setup resolves the directory, reads the project and builds the plan. ok
// is false when the run cannot go on; the Result then says why.
func (r *runner) setup() (Result, bool) {
	selected, err := selectSteps(r.opts.Only, r.opts.Skip)
	if err != nil {
		return Result{Events: []Event{{Step: StepPlan, Level: LevelError, Msg: err.Error(),
			Fix: "name steps from: " + strings.Join(StepNames(), ", ")}}, Exit: 2}, false
	}
	if r.opts.Diff && !r.opts.Check {
		return Result{Events: []Event{{Step: StepPlan, Level: LevelError, Msg: "-diff needs -check",
			Fix: "add -check, or drop -diff"}}, Exit: 2}, false
	}
	if r.wd, err = os.Getwd(); err != nil {
		r.problem(StepPlan, "",
			gen.EnvErrorf("run from a directory that exists", "find the working directory: %v", err))
		return r.result(), false
	}
	if r.root, err = resolveRoot(r.wd, r.opts.Dir); err != nil {
		// A -dir that names no directory of a module is bad usage.
		r.problem(StepPlan, "", err)
		res := r.result()
		res.Exit = 2
		return res, false
	}
	var projErr error
	r.proj, r.declared, projErr = readProject(r.root)
	r.problem(StepPlan, r.root, projErr)
	r.found = discover(r.root)
	for _, e := range r.found.problems {
		r.problem(StepPlan, r.root, e)
	}
	r.units = r.plan(selected, projErr == nil)
	r.planned = map[string]bool{}
	owner := map[string]*unit{}
	for _, u := range r.units {
		for _, out := range u.outputs {
			if first, dup := owner[out]; dup && first != u {
				r.problem(StepPlan, "", r.sharedOutput(out, first, u))
			}
			owner[out] = u
			r.planned[out] = true
		}
	}
	return Result{}, true
}

// sharedOutput reports two units that write the same file: the later one
// would overwrite the earlier, and -check would find one of them stale.
func (r *runner) sharedOutput(out string, first, second *unit) error {
	file, fix := "", "give each package its own output; an error without a better fix is a nano gen bug, report it"
	if r.proj.Env != "" && out == r.abs(r.proj.Env) {
		file, fix = projectFile, "remove Env from "+projectFile+", so each Config package writes the .env.example next to it"
	}
	return gen.Errorf(file, 0, fix, "%s is written by %s %s and by %s %s",
		r.rel(out), first.step.name, r.rel(first.dir), second.step.name, r.rel(second.dir))
}

// selectSteps returns the steps a run covers, as a set of names.
func selectSteps(only, skip []string) (map[string]bool, error) {
	if len(only) > 0 && len(skip) > 0 {
		return nil, errors.New("-only and -skip exclude each other")
	}
	names := StepNames()
	for _, n := range slices.Concat(only, skip) {
		if !slices.Contains(names, n) {
			return nil, fmt.Errorf("unknown step %q", n)
		}
	}
	selected := map[string]bool{}
	for _, n := range names {
		selected[n] = (len(only) == 0 || slices.Contains(only, n)) && !slices.Contains(skip, n)
	}
	return selected, nil
}

// resolveRoot returns the absolute directory of the run: dir, or the root of
// the module that holds wd.
func resolveRoot(wd, dir string) (string, error) {
	if dir != "" {
		abs := dir
		if !filepath.IsAbs(abs) {
			abs = filepath.Join(wd, dir)
		}
		if fi, err := os.Stat(abs); err != nil || !fi.IsDir() {
			return "", gen.Errorf("", 0, "pass -dir with a directory inside a Go module",
				"-dir %s is not a directory", dir)
		}
		if moduleRoot(abs) == "" {
			return "", gen.Errorf("", 0, "pass -dir with a directory inside a Go module",
				"no go.mod in %s or above it", dir)
		}
		return filepath.Clean(abs), nil
	}
	root := moduleRoot(wd)
	if root == "" {
		return "", gen.Errorf("", 0, "run nano gen inside a Go module, or pass -dir",
			"no go.mod in the working directory or above it")
	}
	return root, nil
}

// moduleRoot returns the nearest directory at or above dir that holds a
// go.mod, or "".
func moduleRoot(dir string) string {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// failedNeed returns the first step that s needs and that failed, or "".
func (r *runner) failedNeed(s *step) string {
	for _, need := range s.needs {
		if r.failed[need] {
			return need
		}
	}
	return ""
}

// skipped marks s failed and not run because of need, and reports it once.
func (r *runner) skipped(s *step, need string) {
	if !r.failed[s.name] {
		r.notes = append(r.notes, Event{Step: s.name, Level: LevelSkipped, Msg: "skipped: needs " + need})
	}
	r.failed[s.name] = true
	delete(r.ran, s.name)
}

// runUnit runs unit i, unless a step it needs failed, and records its files.
func (r *runner) runUnit(i int, u *unit) {
	name := u.step.name
	if need := r.failedNeed(u.step); need != "" {
		r.skipped(u.step, need)
		return
	}
	r.ran[name] = true
	out, err := u.step.run(r, u, r.overlay(i))
	if err != nil {
		r.failed[name] = true
		r.problem(name, u.step.base(r, u), err)
		return
	}
	for _, f := range out.files {
		r.sync(name, f)
	}
	r.problem(name, u.step.base(r, u), out.gaps)
}

// overlay returns the files that replace the disk in unit i's package
// loads: the fresh outputs of earlier units under -check, and a stub of each
// existing Go output of a later unit.
func (r *runner) overlay(i int) map[string][]byte {
	ov := map[string][]byte{}
	if r.opts.Check {
		for path, data := range r.fresh {
			if strings.HasSuffix(path, ".go") && dirExists(filepath.Dir(path)) {
				ov[path] = data
			}
		}
	}
	for _, later := range r.units[i+1:] {
		for _, out := range later.outputs {
			if _, done := r.fresh[out]; done || !strings.HasSuffix(out, ".go") {
				continue
			}
			src, err := os.ReadFile(out)
			if err != nil {
				continue // missing: nothing to replace
			}
			if s, ok := stub(src); ok {
				ov[out] = s
			}
		}
	}
	return ov
}

func dirExists(dir string) bool {
	fi, err := os.Stat(dir)
	return err == nil && fi.IsDir()
}

// sync compares one output with the disk and, without Check, writes it.
func (r *runner) sync(step string, f gen.File) {
	path, err := filepath.Abs(f.Path)
	if err != nil {
		r.problem(step, "", gen.EnvErrorf("run from a directory that exists", "resolve %s: %v", f.Path, err))
		return
	}
	r.fresh[path] = f.Data
	have, readErr := os.ReadFile(path)
	level := LevelStale
	switch {
	case readErr == nil && bytes.Equal(have, f.Data):
		return
	case errors.Is(readErr, os.ErrNotExist):
		level = LevelMissing
	case readErr != nil:
		r.problem(step, "", fileError(path, readErr))
		return
	}
	if r.opts.Check {
		ev := Event{Step: step, Level: level, File: r.rel(path), Msg: level + " " + r.rel(path),
			Fix: "run nano gen without -check, then commit the result"}
		if r.opts.Diff && level == LevelStale {
			ev.Diff = diffLines(have, f.Data, diffLimit)
		}
		r.files = append(r.files, ev)
		return
	}
	if err = os.MkdirAll(filepath.Dir(path), 0o750); err == nil {
		//nolint:gosec // generated source is committed and readable like any source file
		err = os.WriteFile(path, f.Data, 0o644)
	}
	if err != nil {
		r.problem(step, "", fileError(path, err))
		return
	}
	r.files = append(r.files, Event{Step: step, Level: LevelWrote, File: r.rel(path), Msg: "wrote " + r.rel(path)})
}

// fileError reports a file the run cannot read, write or delete.
func fileError(path string, err error) *gen.Error {
	return &gen.Error{
		File: path,
		Msg:  err.Error(),
		Fix:  "make the path a writable regular file, or remove what is in its place",
		Err:  gen.ErrEnvironment,
	}
}

// problem records every problem in err as an error event of step, with
// relative paths resolved from base and reported relative to the root.
func (r *runner) problem(step, base string, err error) {
	for _, e := range gen.Errors(err) {
		file := e.File
		if file != "" {
			if !filepath.IsAbs(file) && base != "" {
				file = filepath.Join(base, file)
			}
			file = r.rel(file)
		}
		fix := e.Fix
		if fix == "" {
			fix = "none known; an error without a fix is a nano gen bug, report it"
		}
		r.notes = append(r.notes, Event{Step: step, Level: LevelError, File: file, Line: e.Line, Msg: e.Msg,
			Fix: fix, env: errors.Is(e, gen.ErrEnvironment)})
	}
}

// rel returns path relative to the root, slash-separated.
func (r *runner) rel(path string) string {
	if r.root == "" || !filepath.IsAbs(path) {
		return filepath.ToSlash(path)
	}
	rel, err := filepath.Rel(r.root, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}

func (r *runner) rels(paths []string) []string {
	out := make([]string, len(paths))
	for i, p := range paths {
		out[i] = r.rel(p)
	}
	return out
}

// result orders the events, file results first, and computes the exit code.
func (r *runner) result() Result {
	res := Result{Events: slices.Concat(r.files, r.notes)}
	for _, e := range res.Events {
		switch {
		case e.Level == LevelError && e.env:
			res.Exit = 3
		case res.Exit == 0 && (e.Level == LevelError || e.Level == LevelStale || e.Level == LevelMissing ||
			e.Level == LevelOrphan):
			res.Exit = 1
		}
	}
	return res
}
