package pipeline

import (
	"bufio"
	"errors"
	"go/ast"
	"go/build/constraint"
	"go/parser"
	"go/scanner"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/nanostack-dev/nanostack-framework/gen"
)

const (
	nanoPath = "github.com/nanostack-dev/nanostack-framework/core/nano"
	buildTag = "nanogen"
)

// knownDirectives are the //nano: directives a generator reads.
var knownDirectives = []string{"errors", "error"} //nolint:gochecknoglobals // read-only table.

var (
	// headerPattern matches the first line of a file nano gen wrote, in Go,
	// Markdown or .env syntax, and captures the step.
	headerPattern = regexp.MustCompile(`^(?://|#|<!--) Code generated by nano gen ([a-z]+)\b`)
	// nanoGenPattern matches a go:generate command that runs nano gen, and
	// captures what follows.
	nanoGenPattern = regexp.MustCompile(`(?:^|[\s/])nano\s+gen\b(.*)`)
)

// discovery is what a walk of the root found.
type discovery struct {
	catalogues []pkgFiles // packages with a //nano:errors declaration
	manifests  []pkgFiles // packages whose nanogen file calls nano.Manifest
	headers    []header   // files that start with a nano gen header
	problems   []error    // guards and parse errors
	// complete is false when a Go file did not parse: a declaration in it
	// may be missing, so the orphan scan does not run.
	complete bool
}

// pkgFiles is a package directory and the files that put it in the plan.
type pkgFiles struct {
	dir   string
	files []string
}

// header is a generated file and the step its header names.
type header struct {
	path string
	step string
}

// discover walks root by parsing alone, so it works on a tree that does not
// compile. It skips testdata, vendor, node_modules, hidden directories,
// directories starting with an underscore and nested modules.
func discover(root string) *discovery {
	w := &walker{
		discovery:  &discovery{complete: true},
		fset:       token.NewFileSet(),
		catalogues: map[string][]string{},
		manifests:  map[string][]string{},
	}
	walkErr := filepath.WalkDir(root, func(path string, e fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if e.IsDir() {
			if path != root && skipDir(path, e.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if e.Type().IsRegular() {
			w.visit(path)
		}
		return nil
	})
	d := w.discovery
	if walkErr != nil {
		d.complete = false
		d.problems = append(d.problems, &gen.Error{Msg: "walk the directory: " + walkErr.Error(),
			Fix: "make every directory under it readable", Err: gen.ErrEnvironment})
	}
	d.catalogues = sortedPackages(w.catalogues)
	d.manifests = sortedPackages(w.manifests)
	return d
}

// walker collects a discovery file by file.
type walker struct {
	*discovery
	fset       *token.FileSet
	catalogues map[string][]string // package directory -> files with //nano:errors
	manifests  map[string][]string // package directory -> nanogen files that call nano.Manifest
}

// visit reads one regular file: its header, and for a Go file its
// directives, guards and manifest call.
func (w *walker) visit(path string) {
	if step := headerStep(path); step != "" {
		w.headers = append(w.headers, header{path: path, step: step})
	}
	if !strings.HasSuffix(path, ".go") {
		return
	}
	f, err := parser.ParseFile(w.fset, path, nil, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		w.complete = false
		w.problems = append(w.problems, syntaxProblems(path, err)...)
	}
	if f == nil {
		return
	}
	w.guard(w.fset, path, f)
	if strings.HasSuffix(path, "_test.go") {
		return
	}
	dir := filepath.Dir(path)
	if hasDirective(f, "errors") {
		w.catalogues[dir] = append(w.catalogues[dir], path)
	}
	if isManifest(f) {
		w.manifests[dir] = append(w.manifests[dir], path)
	}
}

// skipDir reports whether the walk skips the directory: it is not part of
// this module's own Go source.
func skipDir(path, name string) bool {
	switch {
	case name == "testdata" || name == "vendor" || name == "node_modules":
		return true
	case strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_"):
		return true
	}
	_, err := os.Stat(filepath.Join(path, "go.mod"))
	return err == nil // a nested module runs its own nano gen
}

func sortedPackages(m map[string][]string) []pkgFiles {
	out := make([]pkgFiles, 0, len(m))
	for dir, files := range m {
		out = append(out, pkgFiles{dir: dir, files: files})
	}
	slices.SortFunc(out, func(a, b pkgFiles) int { return strings.Compare(a.dir, b.dir) })
	return out
}

// headerStep returns the step named by the generated-file header on the
// first line of path, or "".
func headerStep(path string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer func() { _ = f.Close() }()
	line, err := bufio.NewReaderSize(f, 512).ReadSlice('\n')
	if err != nil && !errors.Is(err, bufio.ErrBufferFull) && len(line) == 0 {
		return ""
	}
	m := headerPattern.FindSubmatch(line)
	if m == nil {
		return ""
	}
	return string(m[1])
}

// syntaxProblems turns a parse error into problems at their lines.
func syntaxProblems(path string, err error) []error {
	var list scanner.ErrorList
	if !errors.As(err, &list) {
		return []error{gen.Errorf(path, 0, "fix the syntax error", "%v", err)}
	}
	out := make([]error, 0, len(list))
	for _, e := range list {
		out = append(out, gen.Errorf(path, e.Pos.Line, "fix the syntax error", "%s", e.Msg))
	}
	return out
}

// guard reports the unknown //nano: directives in f and the //go:generate
// lines that run nano gen.
func (d *discovery) guard(fset *token.FileSet, path string, f *ast.File) {
	for _, group := range f.Comments {
		for _, c := range group.List {
			line := fset.Position(c.Slash).Line
			if e := directiveProblem(path, line, c.Text); e != nil {
				d.problems = append(d.problems, e)
			}
			if e := generateProblem(path, line, c.Text); e != nil {
				d.problems = append(d.problems, e)
			}
		}
	}
}

// directiveProblem reports a //nano: directive that no generator reads.
func directiveProblem(path string, line int, text string) error {
	name, ok := strings.CutPrefix(text, "//nano:")
	if !ok {
		return nil
	}
	name, _, _ = strings.Cut(name, " ")
	if slices.Contains(knownDirectives, name) {
		return nil
	}
	return gen.Errorf(path, line, "known directives are //nano:errors and //nano:error",
		"unknown directive //nano:%s", name)
}

// generateProblem reports a //go:generate line that runs nano gen.
func generateProblem(path string, line int, text string) error {
	cmd, ok := strings.CutPrefix(text, "//go:generate ")
	if !ok {
		return nil
	}
	m := nanoGenPattern.FindStringSubmatch(cmd)
	if m == nil {
		return nil
	}
	what := "nano gen"
	if fields := strings.Fields(m[1]); len(fields) > 0 && !strings.HasPrefix(fields[0], "-") {
		what += " " + fields[0]
	}
	return gen.Errorf(path, line, "delete the line; run go tool nano gen",
		"//go:generate runs %s; the pipeline runs this step", what)
}

// hasDirective reports whether f holds the //nano:<name> directive.
func hasDirective(f *ast.File, name string) bool {
	for _, group := range f.Comments {
		for _, c := range group.List {
			if rest, ok := strings.CutPrefix(c.Text, "//nano:"+name); ok && (rest == "" || rest[0] == ' ') {
				return true
			}
		}
	}
	return false
}

// isManifest reports whether f is built only under the nanogen tag and calls
// nano.Manifest.
func isManifest(f *ast.File) bool {
	if !onlyUnderTag(f) {
		return false
	}
	name := ""
	for _, imp := range f.Imports {
		if p, err := strconv.Unquote(imp.Path.Value); err == nil && p == nanoPath {
			name = "nano"
			if imp.Name != nil {
				name = imp.Name.Name
			}
		}
	}
	if name == "" || name == "_" {
		return false
	}
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		if call, isCall := n.(*ast.CallExpr); isCall && !found {
			found = isSelector(call.Fun, name, "Manifest")
		}
		return !found
	})
	return found
}

// isSelector reports whether expr is pkg.sel.
func isSelector(expr ast.Expr, pkg, sel string) bool {
	s, ok := expr.(*ast.SelectorExpr)
	if !ok || s.Sel.Name != sel {
		return false
	}
	x, isIdent := s.X.(*ast.Ident)
	return isIdent && x.Name == pkg
}

// onlyUnderTag reports whether f's //go:build line needs the nanogen tag: it
// holds when every tag is set and fails when only nanogen is missing.
func onlyUnderTag(f *ast.File) bool {
	for _, group := range f.Comments {
		if group.Pos() >= f.Package {
			break
		}
		for _, c := range group.List {
			if !constraint.IsGoBuild(c.Text) {
				continue
			}
			expr, err := constraint.Parse(c.Text)
			if err != nil {
				return false
			}
			return expr.Eval(func(string) bool { return true }) &&
				!expr.Eval(func(tag string) bool { return tag != buildTag })
		}
	}
	return false
}
