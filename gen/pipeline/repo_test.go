// The tests of the repo step, on the db fixture: its package
// internal/repository declares a base on users, and its repo_base.gen.go
// is committed. The db step hits its cache, so no test opens a database.

const repoBase = "internal/repository/repo_base.gen.go"

// The committed base is current; the step runs after errors and before
// config, and -list shows its unit.
func TestRepoStepPlanAndCheck(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	stdout, stderr, code := runDBFixture(t, dir, Options{Check: true}, noDatabase(t))
	wantRun(t, "nano gen -check", code, 0, stdout, "", stderr, "")

	res := List(Options{Dir: dir})
	var plan []string
	for _, e := range res.Events {
		if e.Level == LevelPlan {
			plan = append(plan, e.Msg+" -> "+strings.Join(e.Outputs, ","))
		}
	}
	want := "repo internal/repository -> " + repoBase
	if !slices.Contains(plan, want) {
		t.Fatalf("plan %q has no %q", plan, want)
	}
	names := StepNames()
	if i := slices.Index(names, "repo"); i < 0 || names[i-1] != "errors" || names[i+1] != "config" {
		t.Fatalf("step order %v: repo must run after errors and before config", names)
	}
}

// A stale base is rewritten, and -only repo and -skip db run the step
// without a database.
func TestRepoStepWritesWithoutADatabase(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	write(t, dir, repoBase, "// Code generated by nano gen repo. DO NOT EDIT.\n\npackage repository\n")
	stdout, stderr, code := runDBFixture(t, dir, Options{Check: true, Only: []string{"repo"}}, noDatabase(t))
	wantRun(t, "nano gen -check -only repo", code, 1, stdout, "", stderr,
		"stale "+repoBase+"\n  fix: run nano gen without -check, then commit the result\n")
	stdout, stderr, code = runDBFixture(t, dir, Options{Skip: []string{"db"}}, noDatabase(t))
	wantRun(t, "nano gen -skip db", code, 0, stdout, "wrote "+repoBase+"\n", stderr, "")
}

// Postgres.Scopes reaches the step: a hand-written query of users without
// tenant_id is a warning, printed and in -json, and the run exits 0.
func TestRepoScopeWarning(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	edit(t, dir, "nanogen/project.go", `Postgres: &project.Postgres{Name: "app"}`,
		`Postgres: &project.Postgres{Name: "app", Scopes: []string{"tenant_id"}}`)
	stdout, stderr, code := runDBFixture(t, dir, Options{Check: true}, noDatabase(t))
	wantRun(t, "nano gen -check", code, 0, stdout, "", stderr,
		"warning: internal/repository/users.go:31: ByEmail: condition on users has no tenant_id; this query can "+
			"read or change another tenant's rows\n"+
			"  fix: add u.where.TenantID(…) to the condition, or name it ByEmailInternal for a trusted system path\n")
	res := Run(Options{Dir: dir, Check: true, database: noDatabase(t)})
	var warnings []Event
	for _, e := range res.Events {
		if e.Level == LevelWarning {
			warnings = append(warnings, e)
		}
	}
	if res.Exit != 0 || len(warnings) != 1 || warnings[0].Step != "repo" ||
		warnings[0].File != "internal/repository/users.go" || warnings[0].Line != 31 {
		t.Fatalf("exit %d, warnings %+v", res.Exit, warnings)
	}
}

// A package with no declaration left has an orphan base: -check reports it
// and a run deletes it.
func TestRepoOrphanBase(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	write(t, dir, "internal/repository/users.go", "package repository\n")
	stdout, stderr, code := runDBFixture(t, dir, Options{Check: true}, noDatabase(t))
	wantRun(t, "nano gen -check", code, 1, stdout, "", stderr,
		"orphan "+repoBase+"\n  fix: run nano gen without -check, then commit the result\n")
	stdout, _, code = runDBFixture(t, dir, Options{}, noDatabase(t))
	if code != 0 || stdout != "deleted "+repoBase+"\n" {
		t.Fatalf("nano gen: exit %d, stdout:\n%s", code, stdout)
	}
	if _, err := os.Stat(filepath.Join(dir, repoBase)); !os.IsNotExist(err) {
		t.Fatalf("the orphan base is still there: %v", err)
	}
}

// A failed db step skips repo, which keeps its base: a skipped step's files
// are no orphans.
func TestRepoSkippedWhenDBFails(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	write(t, dir, "migrations/000002_name.up.sql", "ALTER TABLE users ADD COLUMN name text;\n")
	_, stderr, code := runDBFixture(t, dir, Options{}, noDocker)
	if code != 3 || !strings.HasSuffix(stderr, "nano gen repo: skipped: needs db\n") {
		t.Fatalf("exit %d, stderr:\n%s", code, stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, repoBase)); err != nil {
		t.Fatalf("the base of a skipped step is gone: %v", err)
	}
}

// A compile error in the repository package fails the step at its line,
// and the base on disk stays.
func TestRepoCompileError(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	edit(t, dir, "internal/repository/users.go", "u.where.Email(email)", "u.where.Mail(email)")
	_, stderr, code := runDBFixture(t, dir, Options{}, noDatabase(t))
	want := "internal/repository/users.go:32: compile error: u.where.Mail undefined (type usersWhere has no field " +
		"or method Mail)\n  fix: fix the compile error here; nano gen repo needs the package to type-check, " +
		"apart from the names it generates\n"
	if code != 1 || !strings.Contains(stderr, want) {
		t.Fatalf("exit %d, stderr:\n%s\nwant it to contain:\n%s", code, stderr, want)
	}
	if _, err := os.Stat(filepath.Join(dir, repoBase)); err != nil {
		t.Fatalf("a failed repo step deleted its base: %v", err)
	}
}

// accountsFile binds an interface with a derived method on users; it shares
// the base the fixture declares.
const accountsFile = "internal/repository/accounts.go"

const accountsDerived = "internal/repository/accounts_repo.gen.go"

const accounts = `package repository

import (
	"context"

	"github.com/nanostack-dev/nanostack-framework/db/nanorepo"
	"github.com/nanostack-dev/nanostack-framework/db/qrm"
	"github.com/nanostack-dev/nanostack-framework/pkg/functional"

	"example.com/dbapp/internal/db/gen/app/public/model"
	"example.com/dbapp/internal/db/gen/app/public/table"
)

// Accounts reads users by their keys.
type Accounts interface {
	FindByTenantIDAndEmail(ctx context.Context, tenantID, email string) (functional.Option[model.Users], error)
}

func _() { nanorepo.Implement[Accounts, accountsImpl](table.Users, nanorepo.NoMapper[model.Users]) }

type accountsImpl struct{ usersBase }

// NewAccounts returns the accounts on db.
func NewAccounts(db qrm.DB) Accounts { return &accountsImpl{usersBase: newUsersBase(db)} }
`

// A declaring file with a nanorepo.Implement gets its derived file: -list
// plans it, a run writes it, and -check passes after.
func TestRepoDerivedFile(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	write(t, dir, accountsFile, accounts)
	res := List(Options{Dir: dir})
	want := "repo internal/repository -> " + repoBase + "," + accountsDerived
	if !slices.ContainsFunc(res.Events, func(e Event) bool {
		return e.Level == LevelPlan && e.Msg+" -> "+strings.Join(e.Outputs, ",") == want
	}) {
		t.Fatalf("plan %+v has no %q", res.Events, want)
	}
	stdout, stderr, code := runDBFixture(t, dir, Options{}, noDatabase(t))
	wantRun(t, "nano gen", code, 0, stdout, "wrote "+accountsDerived+"\n", stderr, "")
	data, err := os.ReadFile(filepath.Join(dir, accountsDerived))
	if err != nil || !strings.Contains(string(data), "func (r *accountsImpl) FindByTenantIDAndEmail(") {
		t.Fatalf("%s: %v\n%s", accountsDerived, err, data)
	}
	stdout, stderr, code = runDBFixture(t, dir, Options{Check: true}, noDatabase(t))
	wantRun(t, "nano gen -check", code, 0, stdout, "", stderr, "")
}

// An interface that gained a method breaks no step before repo: the errors
// step loads the package with the forward stub of the derived file, which
// declares the new method, in place of the body-stripped stub, whose var _
// line would fail. Only the derived file is stale.
func TestRepoForwardStub(t *testing.T) {
	t.Parallel()
	dir := copyFixtureOf(t, dbFixture)
	write(t, dir, accountsFile, accounts)
	write(t, dir, "internal/repository/errors.go", `package repository

// declarations is the error catalogue of the repository package.
//
//nano:errors namespace=accounts
type declarations interface {
	// No account has the email.
	//
	//nano:error code=account_not_found status=404 title="Account not found"
	AccountNotFound()
}
`)
	if _, stderr, code := runDBFixture(t, dir, Options{}, noDatabase(t)); code != 0 {
		t.Fatalf("nano gen: exit %d, stderr:\n%s", code, stderr)
	}
	edit(t, dir, accountsFile, "type Accounts interface {\n", "type Accounts interface {\n"+
		"\tExistsByTenantIDAndEmail(ctx context.Context, tenantID, email string) (bool, error)\n")
	stdout, stderr, code := runDBFixture(t, dir, Options{Check: true}, noDatabase(t))
	wantRun(t, "nano gen -check", code, 1, stdout, "", stderr,
		"stale "+accountsDerived+"\n  fix: run nano gen without -check, then commit the result\n")
	stdout, stderr, code = runDBFixture(t, dir, Options{}, noDatabase(t))
	wantRun(t, "nano gen", code, 0, stdout, "wrote "+accountsDerived+"\n", stderr, "")
}

