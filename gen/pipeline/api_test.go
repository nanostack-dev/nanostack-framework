// A changed spec makes the server stale. Under -check, validate loads the
// fresh server through the overlay, so the new property is validated before
// anything is written.
func TestStaleAPI(t *testing.T) {
	t.Parallel()
	dir := copyFixture(t)
	edit(t, dir, "api/openapi.yaml", "note: {type: string, maxLength: 3}",
		"note: {type: string, maxLength: 3}\n        alias: {type: string, minLength: 2}")
	stdout, stderr, code := nano(t, dir, "-check")
	wantRun(t, "nano gen -check", code, 1, stdout, "", stderr, `stale api/api.gen.go
stale api/validate.gen.go
  fix: run nano gen without -check, then commit the result
`)

	stdout, stderr, code = nano(t, dir)
	wantRun(t, "nano gen", code, 0, stdout, "wrote api/api.gen.go\nwrote api/validate.gen.go\n", stderr, "")
	server, err := os.ReadFile(filepath.Join(dir, "api", "api.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(server), "// Code generated by nano gen api from openapi.yaml. DO NOT EDIT.\n") ||
		!strings.Contains(string(server), "`json:\"alias,omitempty\"`") {
		t.Errorf("api.gen.go does not hold the new property:\n%s", server[:min(len(server), 600)])
	}
	stdout, stderr, code = nano(t, dir, "-check")
	wantRun(t, "nano gen -check after a run", code, 0, stdout, "", stderr, "")
}

// A spec oapi-codegen rejects fails the api step, and skips validate and
// the steps after it. errors does not need api, so it still runs.
func TestAPIFailureSkipsDependents(t *testing.T) {
	t.Parallel()
	dir := copyFixture(t)
	edit(t, dir, "api/openapi.yaml", "schema: {$ref: '#/components/schemas/Body'}",
		"schema: {$ref: '#/components/schemas/Missing'}")
	edit(t, dir, "greeterr/errors.go", "code=greeting_empty ", "")
	stdout, stderr, code := nano(t, dir, "-check")
	if code != 1 || stdout != "" ||
		!strings.Contains(stderr, "api/openapi.yaml: load the spec: ") ||
		!strings.Contains(stderr, "nano gen validate: skipped: needs api\n") ||
		!strings.Contains(stderr, "greeterr/errors.go:11: ") ||
		!strings.Contains(stderr, "nano gen config: skipped: needs validate\nnano gen wire: skipped: needs config\n") {
		t.Fatalf("exit %d\nstdout:\n%s\nstderr:\n%s", code, stdout, stderr)
	}
}

// A declared client is generated after the server, with PlainTypes, and
// becomes an orphan when the declaration drops it.
func TestClient(t *testing.T) {
	t.Parallel()
	dir := copyFixture(t)
	edit(t, dir, "nanogen/project.go", `Server: project.Package{Dir: "api"},`,
		`Server: project.Package{Dir: "api"},
		Clients: []project.Client{{Dir: "clients/go", Package: "client", PlainTypes: true}},`)
	stdout, stderr, code := nano(t, dir, "-list", "-only", "api")
	wantRun(t, "nano gen -list -only api", code, 0, stdout, `api       api
  in   api/openapi.yaml
  out  api/api.gen.go
  out  clients/go/client.gen.go
`, stderr, "")

	stdout, stderr, code = nano(t, dir, "-check")
	wantRun(t, "nano gen -check", code, 1, stdout, "", stderr, `missing clients/go/client.gen.go
  fix: run nano gen without -check, then commit the result
`)
	stdout, stderr, code = nano(t, dir)
	wantRun(t, "nano gen", code, 0, stdout, "wrote clients/go/client.gen.go\n", stderr, "")
	client, err := os.ReadFile(filepath.Join(dir, "clients", "go", "client.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	const header = "// Code generated by nano gen api from ../../api/openapi.yaml. DO NOT EDIT.\n"
	if !strings.HasPrefix(string(client), header) ||
		!strings.Contains(string(client), "\npackage client\n") ||
		!strings.Contains(string(client), "func NewClient(") {
		t.Errorf("client.gen.go:\n%s", client[:min(len(client), 600)])
	}

	edit(t, dir, "nanogen/project.go",
		`Clients: []project.Client{{Dir: "clients/go", Package: "client", PlainTypes: true}},`, "")
	stdout, stderr, code = nano(t, dir, "-check")
	wantRun(t, "nano gen -check without the client", code, 1, stdout, "", stderr, `orphan clients/go/client.gen.go
  fix: run nano gen without -check, then commit the result
`)
}

