// The declaration of the API is checked before any step runs: outputs stay
// inside the run's directory, a client names its package, and two outputs
// never share a path.
func TestAPIDeclarationErrors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name, server, want string
	}{
		{"neither server nor client", ``,
			"nanogen/project.go:10: API declares neither a server nor a client\n" +
				"  fix: set API.Server.Dir to the server package, or add a client to API.Clients\n"},
		{"server outside", `Server: project.Package{Dir: "../api"},`,
			"nanogen/project.go:12: API.Server.Dir ../api is outside the directory nano gen runs on\n" +
				"  fix: generate under the directory nano gen runs on; " +
				"a module beside it declares its own nanogen/project.go\n"},
		{"client outside", `Server: project.Package{Dir: "api"},
		Clients: []project.Client{{Dir: "../client", Package: "client"}},`,
			"nanogen/project.go:13: API.Clients[0].Dir ../client is outside the directory nano gen runs on\n" +
				"  fix: generate under the directory nano gen runs on; " +
				"a module beside it declares its own nanogen/project.go\n"},
		{"client package", `Server: project.Package{Dir: "api"},
		Clients: []project.Client{{Dir: "clients/go"}},`,
			"nanogen/project.go:13: API.Clients[0].Package \"\" is not a Go package name\n" +
				"  fix: set API.Clients[0].Package to a Go package name\n"},
		{"same output", `Server: project.Package{Dir: "api", File: "gen.go"},
		Clients: []project.Client{{Dir: "api", Package: "api", File: "gen.go"}},`,
			"nanogen/project.go:13: API.Server and API.Clients[0] both write api/gen.go\n" +
				"  fix: give API.Clients[0] its own Dir or File\n"},
		{"file name", `Server: project.Package{Dir: "api", File: "gen/api.go"},`,
			"nanogen/project.go:12: API.Server.File gen/api.go is not a .go file name\n" +
				"  fix: set API.Server.File to a file name such as api.gen.go\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			dir := copyFixture(t)
			edit(t, dir, "nanogen/project.go", `Server: project.Package{Dir: "api"},`, tt.server)
			stdout, stderr, code := nano(t, dir, "-check", "-only", "api")
			wantRun(t, "nano gen -check -only api", code, 1, stdout, "", stderr,
				tt.want+"nano gen api: skipped: needs nanogen/project.go\n")
		})
	}
}

// A //go:generate line that runs oapi-codegen bypasses the api step.
func TestForbiddenOapiCodegenGenerate(t *testing.T) {
	t.Parallel()
	dir := copyFixture(t)
	write(t, dir, "api/generate.go", "package api\n\n"+
		"//go:generate go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.2 -config c.yaml openapi.yaml\n")
	stdout, stderr, code := nano(t, dir, "-check")
	wantRun(
		t,
		"nano gen -check",
		code,
		1,
		stdout,
		"",
		stderr,
		`api/generate.go:3: //go:generate runs oapi-codegen; the pipeline's api step generates the server and the clients
  fix: delete the line; declare the spec in API of nanogen/project.go and run go tool nano gen
`,
	)
}

func TestGenerateGuardPatterns(t *testing.T) {
	t.Parallel()
	for _, tt := range []struct {
		cmd  string
		oapi bool
	}{
		{"go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.2 -config c.yaml s.yaml", true},
		{"go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen --config=codegen.yaml s.yaml", true},
		{"go tool oapi-codegen -config c.yaml s.yaml", true},
		{"oapi-codegen -generate types s.yaml", true},
		{"go run ./cmd/integrationgen", false},
		{"go run example.com/oapi-codegen-extras/cmd/tool", false},
		{"stringer -type=Kind", false},
	} {
		got := oapiCodegenPattern.MatchString(tt.cmd)
		if got != tt.oapi {
			t.Errorf("oapi-codegen match of %q = %v, want %v", tt.cmd, got, tt.oapi)
		}
	}
}
